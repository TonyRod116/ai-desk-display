"""Draw the boot splash with the PC's art code and write it as a compressed C header.

    .venv/bin/python firmware/board/tools/make_splash.py

Output: firmware/board/src/splash_data.h (256-colour palette in RGB565 + run-length
data, row by row). The firmware streams it to the panel at boot, so what you see on
the board is this exact picture. The bottom band (y >= 214) is left empty on purpose:
the firmware writes its status line there ("conectando a la wifi...").
"""
import argparse
import sys
from pathlib import Path

from PIL import Image, ImageDraw, ImageFilter, ImageChops

ROOT = Path(__file__).resolve().parents[3]
sys.path.insert(0, str(ROOT))
from token_tv.themes import face  # noqa: E402


def draw():
    s=3
    im=Image.new('RGB',(320*s,240*s),'#03070c')
    d=ImageDraw.Draw(im)
    def line(points,color,width=1):
        d.line([(int(x*s),int(y*s)) for x,y in points],fill=color,width=width*s,joint='curve')
    # Deliberately sparse circuit paths: quiet negative space around the mark.
    for pts in [[(0,62),(48,62),(65,79),(90,79)],[(0,108),(56,108),(72,92),(90,92)],[(320,66),(270,66),(249,87),(229,87)],[(320,119),(278,119),(257,98),(230,98)]]:
        line(pts,'#12313c')
        x,y=pts[-1]; d.ellipse(((x-2)*s,(y-2)*s,(x+2)*s,(y+2)*s),fill='#285261')
    for x in range(20,310,20):
        for y in range(24,136,20):
            if x<80 or x>240:d.point((x*s,y*s),fill='#26404a')
    # Two cut-metal chevrons, a shared terminal prompt.
    shapes=[([(139,36),(109,65),(109,82),(139,111),(149,101),(123,74),(149,46)],'#55efdc'), ([(181,36),(211,65),(211,82),(181,111),(171,101),(197,74),(171,46)],'#ffb468')]
    light=Image.new('RGB',im.size);g=ImageDraw.Draw(light)
    for pts,c in shapes:g.polygon([(x*s,y*s) for x,y in pts],fill=c)
    im=ImageChops.add(im,light.filter(ImageFilter.GaussianBlur(7*s)).point(lambda v:int(v*.35)))
    d=ImageDraw.Draw(im)
    for pts,c in shapes:d.polygon([(x*s,y*s) for x,y in pts],fill=c)
    d.line([(145*s,84*s),(174*s,84*s)],fill='#f0f5ee',width=4*s)
    d.text((160*s,149*s),'AI DESK DISPLAY',font=face('orbitron.ttf',26*s),fill='#eef7f8',anchor='mm')
    d.text((160*s,181*s),'CODEX  /  CLAUDE',font=face('press-start-2p.ttf',7*s),fill='#8198a7',anchor='mm')
    d.line((125*s,201*s,153*s,201*s),fill='#55efdc',width=s)
    d.line((167*s,201*s,195*s,201*s),fill='#ffb468',width=s)
    im=im.resize((320,240),Image.Resampling.LANCZOS)
    ImageDraw.Draw(im).rectangle((0,214,319,239),fill='black')
    return im


def encode(image):
    quant = image.quantize(256, method=Image.Quantize.MEDIANCUT, dither=Image.Dither.NONE)
    palette = quant.getpalette()[:768]
    colors = []
    for i in range(256):
        r, g, b = palette[i * 3:i * 3 + 3]
        colors.append(((r >> 3) << 11) | ((g >> 2) << 5) | (b >> 3))
    pixels = list(quant.getdata())
    runs = bytearray()
    i = 0
    while i < len(pixels):
        value, count = pixels[i], 1
        while i + count < len(pixels) and pixels[i + count] == value and count < 255:
            count += 1
        runs += bytes((count, value))
        i += count
    return colors, bytes(runs)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--preview", type=Path, help="Optional local PNG preview path")
    args = parser.parse_args()
    image = draw()
    colors, runs = encode(image)
    out = ROOT / 'firmware/board/src/splash_data.h'
    lines = ['// Generated by tools/make_splash.py - do not edit.', '#pragma once', '#include <stdint.h>',
             f'static const uint32_t SPLASH_RLE_LEN = {len(runs)};',
             'static const uint16_t SPLASH_PALETTE[256] = {' + ','.join(f'0x{c:04X}' for c in colors) + '};',
             'static const uint8_t SPLASH_RLE[] = {']
    for k in range(0, len(runs), 24):
        lines.append(','.join(str(b) for b in runs[k:k + 24]) + ',')
    lines.append('};')
    out.write_text('\n'.join(lines) + '\n')
    if args.preview:
        image.save(args.preview)
    print(f'splash: {len(runs)} bytes of run-length data (+512 bytes palette); wrote {out.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
