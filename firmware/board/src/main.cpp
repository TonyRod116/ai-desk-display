// A well-formed frame: right magic, sane size, file length matches. Fills w/h.
static bool frameHeader(File &file, uint16_t &w, uint16_t &h) {
  uint8_t head[8];
  if (file.size() < 8 || file.read(head, 8) != 8 || memcmp(head, "TVF1", 4) != 0) return false;
  w = head[4] | (head[5] << 8);
  h = head[6] | (head[7] << 8);
  if (w == 0 || h == 0 || w > tft.width() || h > tft.height()) return false;
  uint32_t base = 8u + (uint32_t)w * h * 2u;
  if (file.size() == base) return true;
  if (file.size() < base + 6) return false;
  uint8_t tail[8] = {0};
  if (!file.seek(base) || file.read(tail, 6) != 6) return false;
  if (memcmp(tail, "ANIM", 4) == 0 || memcmp(tail, "WAVE", 4) == 0) {   // tag + u32 payload length
    if (file.size() < base + 8 || file.read(tail + 6, 2) != 2) return false;
    uint32_t length = tail[4] | (tail[5] << 8) | ((uint32_t)tail[6] << 16) | ((uint32_t)tail[7] << 24);
    file.seek(8);
    return length >= 4 && length <= MAX_ANIM_BYTES && file.size() == base + 8 + length;
  }
  if (memcmp(tail, "STAR", 4) != 0) return false;
  uint16_t count = tail[4] | (tail[5] << 8);
  file.seek(8);   // leave the cursor where the caller expects it: right after the header
  return count <= 128 && file.size() == base + 6 + 6u * count;
}

static uint16_t fixColor(uint16_t p) {   // the same panel options that apply to the pixels
  if (swapBytes) p = (p >> 8) | (p << 8);
  if (swapRedBlue) p = ((p & 0xF800) >> 11) | (p & 0x07E0) | ((p & 0x001F) << 11);
  return p;
}

static uint16_t towardsWhite(uint16_t c, uint8_t eighths) {   // 8 = pure white
  uint16_t r = (c >> 11) & 31, g = (c >> 5) & 63, b = c & 31;
  r += (31 - r) * eighths / 8; g += (63 - g) * eighths / 8; b += (31 - b) * eighths / 8;
  return (r << 11) | (g << 5) | b;
}

static uint16_t aThird(uint16_t c) {   // a third of its light
  return ((((c >> 11) & 31) / 3) << 11) | ((((c >> 5) & 63) / 3) << 5) | ((c & 31) / 3);
}

// Draw a star in its current step of the cycle. `flaring` says whether the cross has to be repainted: while
// it is lit, and once more on the step after (to give the page's own pixels back).
static void paintStar(const Star &s, bool flaring) {
  const uint8_t look = STAR_LOOK[s.step];
  uint16_t centre = s.base;
  if (look == 1) centre = 0xFFFF;                         // spark: pure white
  else if (look == 2) centre = towardsWhite(s.base, 5);   // glow
  else if (look == 3) centre = aThird(s.base);            // dim: it almost goes out
  tft.drawPixel(s.x, s.y, fixColor(centre));
  if (!flaring) return;
  for (int i = 0; i < 8; i++) {
    const bool inner = i == 1 || i == 2 || i == 5 || i == 6;
    uint16_t c = s.arm[i];
    if (look == 1) c = towardsWhite(c, inner ? 6 : 3);
    else if (look == 2 && inner) c = towardsWhite(c, 2);
    tft.drawPixel(s.x + ARM_X[i], s.y + ARM_Y[i], fixColor(c));
  }
}

static bool pixelOf(File &file, uint16_t w, uint16_t x, uint16_t y, uint16_t &p) {
  uint8_t b[2];
  if (!file.seek(8u + ((uint32_t)y * w + x) * 2u) || file.read(b, 2) != 2) return false;
  p = b[0] | (b[1] << 8);
  return true;
}

// Read the star trailer of the open page (cursor must be right after the pixels), then the page's own
// colours under each cross so the flare can be taken away again exactly.
static void readStars(File &file, uint16_t w, uint16_t h) {
  starCount = 0;
  uint32_t base = 8u + (uint32_t)w * h * 2u;
  if (file.size() <= base + 6 || !file.seek(base)) return;
  uint8_t tail[6];
  if (file.read(tail, 6) != 6 || memcmp(tail, "STAR", 4) != 0) return;
  int count = tail[4] | (tail[5] << 8);
  for (int i = 0; i < count && starCount < MAX_STARS; i++) {
    uint8_t e[6];
    if (file.read(e, 6) != 6) break;
    Star &st = stars[starCount];
    st.x = e[0] | (e[1] << 8);
    st.y = e[2] | (e[3] << 8);
    st.base = e[4] | (e[5] << 8);
    st.step = 0;
    starCount++;
  }
  int kept = 0;
  for (int i = 0; i < starCount; i++) {   // a star too close to an edge, or one the file can't back, is dropped
    Star &st = stars[i];
    bool ok = st.x >= 2 && st.y >= 2 && st.x + 2 < w && st.y + 2 < h;
    for (int a = 0; ok && a < 8; a++) ok = pixelOf(file, w, st.x + ARM_X[a], st.y + ARM_Y[a], st.arm[a]);
    if (ok) stars[kept++] = st;
  }
  starCount = kept;
}

