static bool readScroll(File &file, const uint8_t *tag) {
  const uint32_t length = (uint32_t)tag[4] | ((uint32_t)tag[5]<<8) |
    ((uint32_t)tag[6]<<16) | ((uint32_t)tag[7]<<24);
  if ((length != SCROLL_BYTES && length != ZOOM_SCROLL_BYTES && length != ORIGINAL_SCROLL_BYTES && length != FULL_SCROLL_BYTES) || length > MAX_ANIM_BYTES ||
      file.size() != 153616u+length) return false;
  scrolling.data = (uint8_t *)malloc(length);
  if (!scrolling.data || !readBytes(file,scrolling.data,length)) { freeAnim(); return false; }
  const uint8_t *p = scrolling.data;
  const bool fullscreen=p[0] == 4, original=p[0] == 3 || fullscreen, zoom=p[0] == 2 || original;
  if ((p[0] != 1 && p[0] != 2 && p[0] != 3 && !fullscreen) ||
      length != (fullscreen ? FULL_SCROLL_BYTES : original ? ORIGINAL_SCROLL_BYTES : zoom ? ZOOM_SCROLL_BYTES : SCROLL_BYTES) ||
      p[1] != 0 || le16u(p+2) != SCROLL_W || le16u(p+4) != SCROLL_H ||
      le16u(p+6) != SCROLL_TOP || le16u(p+8) != SCROLL_MS || le16u(p+10) != SCROLL_SPEED ||
      le16u(p+12) != (original ? ORIGINAL_RIDER_W : zoom ? ZOOM_RIDER_W : RIDER_W) ||
      le16u(p+14) != (original ? ORIGINAL_RIDER_H : zoom ? ZOOM_RIDER_H : RIDER_H) || le16u(p+16) != RIDER_X ||
      le16u(p+18) != (original ? ORIGINAL_RIDER_FRAMES : zoom ? ZOOM_RIDER_FRAMES : RIDER_FRAMES)) { freeAnim(); return false; }
  scrolling.version=p[0];
  p += 20;
  for (int i=0; i<256; i++, p+=2) scrolling.palette[i]=le16u(p);
  scrolling.heights=p;
  for (int x=0; x<SCROLL_W; x++) if (p[x]<48 || p[x]>=SCROLL_H) { freeAnim(); return false; }
  p += SCROLL_W;
  scrolling.pixels=p;
  scrolling.rider=p+SCROLL_W*SCROLL_H;
  scrolling.coin=original ? scrolling.rider+ORIGINAL_RIDER_FRAMES*(ORIGINAL_RIDER_W/2)*(ORIGINAL_RIDER_H/2)*2u : nullptr;
  scrolling.shell=original ? scrolling.coin+8u*16u*2u : nullptr;
  scrolling.usedBlock=original ? scrolling.shell+16u*16u*2u : nullptr;
  scrolling.blockBackdrops=original ? scrolling.usedBlock+16u*16u*2u : nullptr;
  scrolling.hudPalette=fullscreen ? scrolling.blockBackdrops+2u*16u*18u*2u : nullptr;
  scrolling.hudIndices=fullscreen ? scrolling.hudPalette+64u*2u : nullptr;
  regionPixels=320*SCROLL_BAND_ROWS;
  region=(uint16_t *)malloc(regionPixels*2);
  if (!region) { freeAnim(); return false; }
  if (!scrollEpochSet) { scrollEpoch=animationClock.time(millis()); scrollEpochSet=true; }
  scrolling.started=scrollEpoch;
  const int frameMs=scrolling.version >= 2 ? SCROLL_SMOOTH_MS : SCROLL_FRAME_MS;
  scrolling.lastStep=(uint32_t(animationClock.time(millis())-scrolling.started))/frameMs;
  scrolling.active=true;
  animating=true;
  scrollLastUs=scrollMaxUs=scrollFrames=0;
  return true;
}

static void drawScroll(unsigned long frameStep) {
  if (!scrolling.active || !region) return;
  const unsigned long began=micros();
  const bool fullscreen=scrolling.version == 4, original=scrolling.version >= 3, zoom=scrolling.version >= 2;
  const unsigned long step=zoom ? frameStep/4 : frameStep;
  const int quarter=zoom ? frameStep%4 : 0;
  const int actorW=original ? ORIGINAL_RIDER_W : zoom ? ZOOM_RIDER_W : RIDER_W;
  const int actorH=original ? ORIGINAL_RIDER_H : zoom ? ZOOM_RIDER_H : RIDER_H;
  const int camera=zoom ? ((step%384)*ZOOM_CAMERA_SPEED + quarter)%(SCROLL_W*ZOOM_SCALE) : 0;
  const int offset=zoom ? camera/ZOOM_SCALE : (step*SCROLL_SPEED/2)%SCROLL_W;
  const int foot=zoom ? ((camera+RIDER_X+actorW/2)/ZOOM_SCALE)%SCROLL_W
                      : (offset+(RIDER_X+actorW/2)/2)%SCROLL_W;
  static const uint8_t jump[] = {0,4,8,14,20,26,32,38,42,44,
                                 44,44,44,44,44,44,44,44,44,44,44,44,44,44,
                                 42,38,32,26,20,14,8,4,2,0};
  static const uint8_t hop[] = {0,6,12,18,24,33,24,18,12,6,0};
  static const uint8_t originalHop[] = {0,3,6,9,11,14,11,9,6,3,0};
  static const uint8_t originalJump[] = {0,16,40,63,83,96,99,96,82,61,36,10,0};
  static const uint8_t coinMask[] = {12,30,63,63,63,63,63,30,12};
  const int zoomPhase=(int)(step%192);
  int leap=0;
  if (zoom) {
    auto leapAt = [&](int p) {
      const int phase=p-54, blockHop=p-99;
      if (original && phase>=0 && phase<(int)sizeof(originalJump)) return (int)originalJump[phase];
      if (!original && phase>=0 && phase<=27) return (312*phase*(27-phase)+364)/(27*27);
      if (blockHop>=0 && blockHop<(int)sizeof(hop)) return (int)(original ? originalHop[blockHop] : hop[blockHop]);
      return 0;
    };
    leap=leapAt(zoomPhase);
    if (quarter) {
      // Do not enter the block during the positions immediately before it
      // rises: at the next logical step Mario touches it and it moves up.
      if (zoomPhase != 103) leap=(leap*(4-quarter)+leapAt((zoomPhase+1)%192)*quarter)/4;
    }
  } else {
    const int phase=(int)(step%256)-52;
    if (phase>=0 && phase<(int)sizeof(jump)*2) {
      const int index=phase/2;
      leap=jump[index];
      if (phase%2) leap=(leap+(index+1<(int)sizeof(jump) ? jump[index+1] : 0))/2;
    }
  }
  int groundY=zoom ? SCROLL_TOP+ZOOM_SCALE*(scrolling.heights[foot]-ZOOM_ORIGIN)
                   : SCROLL_TOP+2*scrolling.heights[foot];
  const int airPhase=(zoomPhase-54)*4+quarter;
  const int airDuration=(original ? 12 : 27)*4;
  if (zoom && airPhase>=0 && airPhase<=airDuration) {
    const unsigned long start=step-airPhase/4;
    const int firstCamera=(start*ZOOM_CAMERA_SPEED)%(SCROLL_W*ZOOM_SCALE);
    const int lastCamera=((start+airDuration/4)*ZOOM_CAMERA_SPEED)%(SCROLL_W*ZOOM_SCALE);
    const int first=((firstCamera+RIDER_X+actorW/2)/ZOOM_SCALE)%SCROLL_W;
    const int last=((lastCamera+RIDER_X+actorW/2)/ZOOM_SCALE)%SCROLL_W;
    const int change=ZOOM_SCALE*((int)scrolling.heights[last]-(int)scrolling.heights[first])*airPhase;
    groundY=SCROLL_TOP+ZOOM_SCALE*(scrolling.heights[first]-ZOOM_ORIGIN)+change/airDuration;
  }
  const int shellWorld=step%384<192 ? 217 : 473;
  const int shellLeft=651-10*zoomPhase-(10*quarter)/4;
  const int shellTop=SCROLL_TOP+ZOOM_SCALE*(scrolling.heights[shellWorld]-ZOOM_ORIGIN)-32;
  if (original && quarter && shellLeft<RIDER_X+actorW && shellLeft+32>RIDER_X) {
    // Keep the interpolated landing clear until the shell has fully passed.
    leap=max(leap,groundY-shellTop);
  }
  const int actorY=groundY-actorH-leap;
  int frame=zoom && leap ? 4 : (step/2)%RIDER_FRAMES;
  if (original && leap) {
    const int flight=zoomPhase>54 && zoomPhase<67 ? zoomPhase-54 : zoomPhase-99;
    frame=flight<=2 ? 4 : flight<=4 ? 5 : flight<=8 ? 6 : 7;
  }
  const int sourceW=original ? actorW/2 : actorW, sourceH=original ? actorH/2 : actorH;
  const uint8_t *pose=scrolling.rider+frame*sourceW*sourceH*2u;
  const int coinAge=zoom ? zoomPhase-104 : -1;
  const bool coinActive=coinAge>=0 && coinAge<16;
  const bool blockBump=coinActive && coinAge<2;
  const int hitBlock=step%384<192 ? 157 : 413;
  const int blockLeft=hitBlock*ZOOM_SCALE-camera;
  const int blockTop=SCROLL_TOP+ZOOM_SCALE*(36-ZOOM_ORIGIN);
  const int blockSize=original ? 48 : 42;
  const int coinTop=blockTop-5-min(coinAge*4+(coinActive ? quarter : 0),original ? 48 : 36);
  // Each source row occupies two or three LCD rows. Reuse its clean, scaled
  // background before composing the independently moving sprites and HUD.
  static uint16_t backgroundLine[320];
  int cachedWorldY=-1;
  for (int band=fullscreen ? -SCROLL_TOP : 0; band<SCROLL_H*2; band+=SCROLL_BAND_ROWS) {
    for (int row=0; row<SCROLL_BAND_ROWS; row++) {
      const int y=SCROLL_TOP+band+row;
      const int worldY=fullscreen ? ZOOM_ORIGIN-SCROLL_TOP/ZOOM_SCALE+y/ZOOM_SCALE
                                 : zoom ? ZOOM_ORIGIN+(band+row)/ZOOM_SCALE : (band+row)/2;
      const uint8_t *world=scrolling.pixels+worldY*SCROLL_W;
      uint16_t *line=region+row*320;
      if (worldY != cachedWorldY) {
        if (zoom) {
          int x=0, sample=offset, repeat=ZOOM_SCALE-camera%ZOOM_SCALE;
          while (x<320) {
            const uint16_t color=scrolling.palette[world[sample]];
            for (int n=0; n<repeat && x<320; n++) backgroundLine[x++]=color;
            sample=(sample+1)%SCROLL_W;
            repeat=ZOOM_SCALE;
          }
        } else {
          for (int x=0; x<160; x++) {
            const uint16_t color=scrolling.palette[world[(offset+x)%SCROLL_W]];
            backgroundLine[2*x]=backgroundLine[2*x+1]=color;
          }
        }
        cachedWorldY=worldY;
      }
      memcpy(line, backgroundLine, sizeof(backgroundLine));
      if (original) {
        if (shellLeft<320 && shellLeft+32>0) {
          if (y>=shellTop && y<shellTop+32) {
            const int sy=(y-shellTop)/2;
            for (int col=0; col<32; col++) {
              const int x=shellLeft+col;
              const uint16_t color=le16u(scrolling.shell+2*(sy*16+col/2));
              if (x>=0 && x<320 && color != ANIM_KEY) line[x]=color;
            }
          }
        }
      }
      if (original && zoomPhase>=104 && blockLeft<320 && blockLeft+48>0) {
        if (y>=blockTop-3 && y<blockTop+51) {
          const int sy=(y-(blockTop-3))/3;
          const uint8_t *backdrop=scrolling.blockBackdrops+(step%384<192 ? 0 : 16u*18u*2u);
          for (int x=max(0,blockLeft); x<min(320,blockLeft+48); x++) {
            line[x]=le16u(backdrop+2*(sy*16+(x-blockLeft)/3));
          }
        }
        const int usedTop=blockTop-(blockBump ? 3 : 0);
        if (y>=usedTop && y<usedTop+48) {
          const int sy=(y-usedTop)/3;
          for (int x=max(0,blockLeft); x<min(320,blockLeft+48); x++) {
            const uint16_t color=le16u(scrolling.usedBlock+2*(sy*16+(x-blockLeft)/3));
            if (color != ANIM_KEY) line[x]=color;
          }
        }
      }
      if (!original && blockBump && y>=blockTop-3 && y<blockTop+blockSize) {
        const int sourceY=min(worldY+1,original ? 52 : 50);
        const uint8_t *source=scrolling.pixels+sourceY*SCROLL_W;
        for (int x=max(0,blockLeft); x<min(320,blockLeft+blockSize); x++) {
          const int sourceX=((camera+x)/ZOOM_SCALE)%SCROLL_W;
          line[x]=scrolling.palette[source[sourceX]];
        }
      }
      if (original && coinActive && y>=coinTop && y<coinTop+48 && y<blockTop-(blockBump ? 3 : 0)) {
        const int sy=(y-coinTop)/3;
        for (int col=0; col<24; col++) {
          const int x=blockLeft+12+col;
          const uint16_t color=le16u(scrolling.coin+2*(sy*8+col/3));
          if (x>=0 && x<320 && color != ANIM_KEY) line[x]=color;
        }
      } else if (!original && coinActive && y>=coinTop && y<coinTop+18 && y<blockTop-(blockBump ? 3 : 0)) {
        const uint8_t mask=coinMask[(y-coinTop)/2];
        for (int col=0; col<12; col++) {
          const int x=blockLeft+15+col, bit=col/2;
          if (x>=0 && x<320 && (mask & (1<<(5-bit)))) {
            line[x]=bit==1 ? 0xffd6 : (bit==0 || bit==5) ? 0x9ac4 : 0xff0b;
          }
        }
      }
      if (y>=actorY && y<actorY+actorH) {
        const int sy=y-actorY;
        for (int sx=0; sx<actorW; sx++) {
          const uint16_t color=le16u(pose+2*((original ? sy/2 : sy)*sourceW+(original ? sx/2 : sx)));
          if (color != ANIM_KEY) line[RIDER_X+sx]=color;
        }
      }
      if (fullscreen && y<SCROLL_TOP) {
        const uint8_t *indices=scrolling.hudIndices+y*(320*6/8);
        for (int x=0; x<320; x+=4) {
          const uint8_t a=*indices++, b=*indices++, c=*indices++;
          const uint8_t entry[4] = {(uint8_t)(a&63), (uint8_t)((a>>6)|((b&15)<<2)),
                                    (uint8_t)((b>>4)|((c&3)<<4)), (uint8_t)(c>>2)};
          for (int j=0; j<4; j++) if (entry[j]) line[x+j]=le16u(scrolling.hudPalette+2*entry[j]);
        }
      }
    }
    pushRegion(0,SCROLL_TOP+band,320,SCROLL_BAND_ROWS,region);
  }
  scrollLastUs=micros()-began;
  scrollMaxUs=max(scrollMaxUs,scrollLastUs);
  ++scrollFrames;
}

static int floorDivide(int n, int d) { return n >= 0 ? n / d : -((-n + d - 1) / d); }

static int waveEdge(int y) {
  static const int16_t coast[][2] = {{124,173},{132,158},{144,146},{152,126},
    {160,123},{170,108},{180,104},{190,94},{200,78},{210,72},{220,78},{239,77}};
  for (int i = 0; i < 11; i++) {
    if (y <= coast[i+1][0]) return coast[i][1] +
      floorDivide((coast[i+1][1]-coast[i][1])*(y-coast[i][0]), coast[i+1][0]-coast[i][0]);
  }
  return 77;
}

static void cacheBeach(File &file) {
  // Allocate each band separately so fragmented heap can still hold the full
  // photograph. Never spend the memory reserved for Wi-Fi and control requests.
  const size_t rowBytes = 320u*2u;
  const size_t freeBytes = ESP.getFreeHeap(), largest = ESP.getMaxAllocHeap();
  waveCacheFree = freeBytes; waveCacheLargest = largest; waveCacheAttemptAt = millis();
  size_t budget = freeBytes > BEACH_HEAP_RESERVE ? freeBytes-BEACH_HEAP_RESERVE : 0u;
  if (budget < rowBytes*BEACH_BAND_ROWS) { waveCacheStatus = 1; return; }
  if (!file.seek(8u+(uint32_t)BEACH_TOP*rowBytes)) {
    waveCacheStatus = 3; return;
  }
  for (int i=0; i<BEACH_BANDS; i++) {
    const size_t rows = min(BEACH_BAND_ROWS, BEACH_ROWS-i*BEACH_BAND_ROWS);
    const size_t bytes = rowBytes*rows;
    if (bytes > budget || bytes > ESP.getMaxAllocHeap()) break;
    uint8_t *band = (uint8_t *)malloc(bytes);
    if (!band) break;
    if (file.read(band, bytes) != bytes) {
      free(band);
      for (int j=0; j<i; j++) { free(ocean.beachBands[j]); ocean.beachBands[j]=nullptr; }
      ocean.cachedRows=0; waveCacheStatus=4; return;
    }
    ocean.beachBands[i]=band;
    ocean.cachedRows += rows;
    budget -= bytes;
  }
  waveCacheStatus = ocean.cachedRows ? 5 : 2;
}

static bool readWave(File &file, const uint8_t *tag) {
  const uint32_t length = (uint32_t)tag[4] | ((uint32_t)tag[5]<<8) |
    ((uint32_t)tag[6]<<16) | ((uint32_t)tag[7]<<24);
  const uint32_t fixed = 12u + WAVE_ROWS*2u + 512u + 2u*(320u*WAVE_ROWS/8u);
  if (length < 12u || length > MAX_ANIM_BYTES || file.size() != 153616u+length) return false;
  ocean.data = (uint8_t *)malloc(length);
  if (!ocean.data) return false;
  if (!readBytes(file, ocean.data, length)) { freeAnim(); return false; }
  const uint8_t *p = ocean.data;
  const int version = p[0];
  const bool beach = version == 2 || version == 3;
  const bool hasBoat = version == 3 && p[1] == 1;
  if ((version != 1 && !beach) || (p[1] != 0 && !hasBoat) ||
      le16u(p+2) != (beach ? BEACH_TOP : WAVE_TOP) ||
      le16u(p+4) != (beach ? BEACH_ROWS : WAVE_ROWS) ||
      le16u(p+6) != WAVE_MS || le16u(p+8) != WAVE_STEPS ||
      (version == 2 && le16u(p+10) != 0) ||
      (version == 3 && le16u(p+10) != 2)) { freeAnim(); return false; }
  ocean.version = version;
  ocean.colour = le16u(p+10);
  p += 12;
  ocean.boat = nullptr;
  if (beach) {
    const uint32_t filmSize = 12u+512u+BEACH_W*BEACH_H*BEACH_FRAMES;
    const uint32_t boatSize = hasBoat ? 512u+BOAT_W*BOAT_H*BOAT_FRAMES : 0;
    if (length != filmSize+boatSize) { freeAnim(); return false; }
    for (int i = 0; i < 256; i++, p += 2) ocean.palette[i] = le16u(p);
    ocean.indices = p;
    p += BEACH_W*BEACH_H*BEACH_FRAMES;
    if (hasBoat) {
      for (int i = 0; i < 256; i++, p += 2) ocean.boatPalette[i] = le16u(p);
      ocean.boat = p;
    }
    if (version == 3) {
      // Find the union of changed pixels in each band before compacting the
      // film. Entirely still parts of any photograph can then stay untouched.
      const size_t stride = BEACH_W*BEACH_H;
      for (int i=0; i<BEACH_BANDS; i++) {
        ocean.beachLeft[i]=320; ocean.beachRight[i]=0;
      }
      for (int y=0; y<BEACH_H; y++) for (int x=0; x<BEACH_W; x++) {
        const size_t pos=(size_t)y*BEACH_W+x;
        const uint16_t base=ocean.palette[ocean.indices[pos]];
        bool changes=false;
        for (int frame=1; frame<BEACH_FRAMES && !changes; frame++)
          changes=ocean.palette[ocean.indices[frame*stride+pos]] != base;
        if (changes) {
          const int band=(y*2)/BEACH_BAND_ROWS;
          ocean.beachLeft[band]=min((int)ocean.beachLeft[band],x*2);
          ocean.beachRight[band]=max((int)ocean.beachRight[band],x*2+2);
        }
      }
      // Compact in place: allocating a second copy first needs extra heap at
      // precisely the moment when the full film is already using the most.
      // Keep the baseline, three source frames and boat; the other frames are
      // read on demand. Palettes have already been copied into ocean above.
      const size_t boatBytes = hasBoat ? BOAT_W*BOAT_H*BOAT_FRAMES : 0;
      const size_t compactBytes = BEACH_FILM_SLOTS*stride+boatBytes;
      memmove(ocean.data, ocean.indices, BEACH_FILM_SLOTS*stride);
      if (hasBoat) memmove(ocean.data+BEACH_FILM_SLOTS*stride, ocean.boat, boatBytes);
      // A failed shrink keeps the original allocation valid; the compacted
      // content still works, just with less memory available for the cache.
      uint8_t *compact = (uint8_t *)realloc(ocean.data, compactBytes);
      if (compact) ocean.data = compact;
      ocean.indices = ocean.data;
      ocean.boat = hasBoat ? ocean.data+BEACH_FILM_SLOTS*stride : nullptr;
      ocean.streamFilm = true;
      for (int i=0; i<BEACH_FILM_SLOTS-1; i++) ocean.filmIds[i]=i+1;
    }
    ocean.keep = ocean.glass = nullptr;
  } else {
    if (length < fixed) { freeAnim(); return false; }
    uint32_t count = 0;
    for (int y = 0; y < WAVE_ROWS; y++, p += 2) {
      ocean.starts[y] = le16u(p);
      if (ocean.starts[y] >= 320) { freeAnim(); return false; }
      ocean.offsets[y] = count;
      count += 320-ocean.starts[y];
    }
    if (length != fixed+count) { freeAnim(); return false; }
    for (int i = 0; i < 256; i++, p += 2) ocean.palette[i] = le16u(p);
    ocean.indices = p;
    ocean.keep = p+count;
    ocean.glass = ocean.keep+320*WAVE_ROWS/8;
  }
  regionPixels = 320*(beach ? BEACH_BAND_ROWS : 8);
  region = (uint16_t *)malloc(regionPixels*2);
  if (!region) { freeAnim(); return false; }
  if (beach) {
    // A small optional saturation lookup avoids clamping every channel of
    // every full-resolution pixel on every frame. Low memory uses the exact
    // original arithmetic instead; the source photo is never downsampled.
    ocean.clampLut = (uint8_t *)malloc(BEACH_CLAMP5+BEACH_CLAMP6);
    if (ocean.clampLut) {
      for (int d=-31; d<=31; d++) for (int c=0; c<32; c++)
        ocean.clampLut[(d+31)*32+c] = max(0,min(31,c+d));
      for (int d=-63; d<=63; d++) for (int c=0; c<64; c++)
        ocean.clampLut[BEACH_CLAMP5+(d+63)*64+c] = max(0,min(63,c+d));
    }
  }
  if (ocean.boat) {
    // The unchanging photograph was previously read in 56 separate seeks on
    // every frame. A small optional cache keeps the same pixels and falls back
    // to the original file reads if memory is tight.
    ocean.boatBase = (uint16_t *)malloc(BOAT_W*BOAT_H*2u);
    if (ocean.boatBase && !readRect(file, BOAT_X, BOAT_Y, BOAT_W, BOAT_H, ocean.boatBase)) {
      free(ocean.boatBase);
      ocean.boatBase = nullptr;
    }
  }
  waveCacheStatus = 0; waveCacheFree = waveCacheLargest = waveCacheAttemptAt = 0;
  if (beach) cacheBeach(file);
  ocean.lastStep = 0;
  ocean.started = animationClock.time(millis());
  ocean.active = true;
  animating = true;
  waveLastUs = waveMaxUs = 0;
  waveFrames = 0;
  waveReadUs = waveComposeUs = wavePushUs = waveBoatUs = waveLoopUs = waveIndicatorUs = 0;
  wavePreviousFrameMs = waveGapMs = waveMaxGapMs = waveSlowFrames = 0;
  return true;
}

static uint16_t wavePixel(int x, int y) {
  return ocean.palette[ocean.indices[ocean.offsets[y]+x-ocean.starts[y]]];
}

// Bilinear RGB565 sampling retains the photograph's fine one-pixel detail.
static uint16_t waveSample(int xq, int yq) {
  yq = max(0, min((WAVE_ROWS-1)*256, yq));
  const int y = yq/256, fy = yq%256, y1 = min(WAVE_ROWS-1, y+1);
  xq = max((int)max(ocean.starts[y], ocean.starts[y1])*256, min(319*256, xq));
  const int x = xq/256, fx = xq%256, x1 = min(319, x+1);
  const uint16_t a = wavePixel(x,y), b = wavePixel(x1,y), c = wavePixel(x,y1), d = wavePixel(x1,y1);
  uint16_t out = 0;
  const int shifts[] = {11,5,0}, masks[] = {31,63,31};
  for (int i = 0; i < 3; i++) {
    const int shift = shifts[i], mask = masks[i];
    const int ab = ((a>>shift)&mask)*(256-fx)+((b>>shift)&mask)*fx;
    const int cd = ((c>>shift)&mask)*(256-fx)+((d>>shift)&mask)*fx;
    out |= ((ab*(256-fy)+cd*fy+32768)/65536)<<shift;
  }
  return out;
}

// Two travelling foam crests per loop, with little gaps so they break up
// naturally. The rest of the sea ripples independently underneath them.
static uint8_t waveFoam(int x, int yy, int shore, int step) {
  const int distance = x-shore;
  if (distance < 0) return 0;
  const int bend = ((WAVE_SIN[(yy*2)&127]+128)>>3) + ((WAVE_SIN[(yy*5)&127]+128)>>4);
  const int phase = (distance*4+step*8+bend)&255;
  if (phase >= 48) return 0;
  const int texture = WAVE_SIN[(yy*7+x*3+step*2)&127]+128;
  if (texture < 28) return 0;
  const int strength = 70+80*yy/(WAVE_ROWS-1);
  return ((48-phase)*strength/48)*(80+texture)/336;
}

static uint16_t beachAdjust(uint16_t c, int dr, int dg, int db) {
  const int r = max(0,min(31,((c>>11)&31)+dr));
  const int g = max(0,min(63,((c>>5)&63)+dg));
  const int b = max(0,min(31,(c&31)+db));
  return (r<<11)|(g<<5)|b;
}

static const uint8_t *beachFilmFrame(File &file, int frame, int keepA, int keepB) {
  const size_t stride = BEACH_W*BEACH_H;
  if (!ocean.streamFilm || frame == 0) return ocean.indices+frame*stride;
  for (int slot=0; slot<BEACH_FILM_SLOTS-1; slot++)
    if (ocean.filmIds[slot] == frame) return ocean.indices+(slot+1)*stride;
  for (int slot=0; slot<BEACH_FILM_SLOTS-1; slot++) {
    if (ocean.filmIds[slot] == keepA || ocean.filmIds[slot] == keepB) continue;
    uint8_t *destination = ocean.data+(slot+1)*stride;
    ocean.filmIds[slot]=255; // never use a partial read as an animation frame
    if (!file.seek(BEACH_FILM_OFFSET+(uint32_t)frame*stride) || file.read(destination,stride) != stride) return nullptr;
    ocean.filmIds[slot]=frame;
    return destination;
  }
  return nullptr;
}

static void drawBoat(int step, File &file) {
  if (!ocean.boat) return;
  const int stride = BOAT_W*BOAT_H, first = step/16, mix = step%16;
  const uint8_t *zero = ocean.boat, *a = zero+first*stride;
  const uint8_t *b = zero+((first+1)%BOAT_FRAMES)*stride;
  if (ocean.boatBase) memcpy(region, ocean.boatBase, BOAT_W*BOAT_H*2u);
  for (int y = 0; y < BOAT_H; y++) {
    if (!ocean.boatBase && (!file.seek(8u+((uint32_t)(BOAT_Y+y)*320u+BOAT_X)*2u) ||
        file.read((uint8_t *)(region+y*BOAT_W), BOAT_W*2u) != BOAT_W*2u)) return;
    for (int x = 0; x < BOAT_W; x++) {
      const int pos = y*BOAT_W+x;
      const uint16_t c0 = ocean.boatPalette[zero[pos]], ca = ocean.boatPalette[a[pos]], cb = ocean.boatPalette[b[pos]];
      const int dr = (((ca>>11)&31)*(16-mix)+((cb>>11)&31)*mix+8)/16-((c0>>11)&31);
      const int dg = (((ca>>5)&63)*(16-mix)+((cb>>5)&63)*mix+8)/16-((c0>>5)&63);
      const int db = ((ca&31)*(16-mix)+(cb&31)*mix+8)/16-(c0&31);
      if (!(dr || dg || db)) continue;
      region[pos] = beachAdjust(region[pos],dr,dg,db);
    }
  }
  pushRegion(BOAT_X,BOAT_Y,BOAT_W,BOAT_H,region);
}

static void drawBeach(int step, int boatStep, File &file) {
  const unsigned long began = micros();
  const unsigned long frameAt = millis();
  unsigned long readUs = 0, composeUs = 0, pushUs = 0, stamp = 0;
  int nextFileBand = -1;
  // WAVE3 samples the current time more finely so a 45 ms hardware frame is
  // not forced onto a 25 ms grid. WAVE2 keeps its exact original poses.
  const int phase = ocean.version == 3 ? step : step*(BEACH_SUBSTEPS/8);
  const int first = phase/BEACH_SUBSTEPS, mix = phase%BEACH_SUBSTEPS;
  const uint8_t *zero = ocean.indices;
  const int next=(first+1)%BEACH_FRAMES;
  const uint8_t *a = beachFilmFrame(file,first,first,next), *b = beachFilmFrame(file,next,first,next);
  if (!a || !b) return;
  for (int band = 0; band < BEACH_ROWS; band += BEACH_BAND_ROWS) {
    const int rows = min(BEACH_BAND_ROWS, BEACH_ROWS-band);
    const int bandIndex=band/BEACH_BAND_ROWS;
    const int left=ocean.version == 3 ? ocean.beachLeft[bandIndex] : 0;
    const int right=ocean.version == 3 ? ocean.beachRight[bandIndex] : 320;
    const int width=right-left;
    if (width <= 0) continue;
    const size_t bytes = rows*320u*2u;
    stamp = micros();
    if (ocean.beachBands[bandIndex]) {
      memcpy(region, ocean.beachBands[bandIndex], bytes);
    } else {
      if (nextFileBand != band && !file.seek(8u+(uint32_t)(BEACH_TOP+band)*320u*2u)) return;
      if (file.read((uint8_t *)region, bytes) != bytes) return;
      nextFileBand=band+rows;
    }
    readUs += micros()-stamp;
    stamp = micros();
    for (int r = 0; r < rows; r += 2) {
      const int yy = (band+r)/2, fade = min(8,yy);
      for (int x = left/2; x < right/2; x++) {
        const int pos = yy*BEACH_W+x;
        const uint16_t c0 = ocean.palette[zero[pos]], ca = ocean.palette[a[pos]], cb = ocean.palette[b[pos]];
        if (ca == c0 && cb == c0) continue;
        // Spread quantisation thresholds spatially. Otherwise small colour
        // changes make thousands of water pixels jump at the same instant.
        // The stable pattern is exact at source frames and the loop seam.
        const int bias = ocean.version == 3 ? (pos*73+19)&(BEACH_SUBSTEPS-1) : BEACH_SUBSTEPS/2;
        int dr = ((((ca>>11)&31)*(BEACH_SUBSTEPS-mix)+((cb>>11)&31)*mix+bias)/BEACH_SUBSTEPS)-((c0>>11)&31);
        int dg = ((((ca>>5)&63)*(BEACH_SUBSTEPS-mix)+((cb>>5)&63)*mix+bias)/BEACH_SUBSTEPS)-((c0>>5)&63);
        int db = (((ca&31)*(BEACH_SUBSTEPS-mix)+(cb&31)*mix+bias)/BEACH_SUBSTEPS)-(c0&31);
        // Only the first eight source rows need the horizon fade.
        if (fade < 8) { dr = dr*fade/8; dg = dg*fade/8; db = db*fade/8; }
        if (!(dr || dg || db)) continue;
        if (ocean.clampLut) {
          const uint8_t *rr=ocean.clampLut+(dr+31)*32;
          const uint8_t *gg=ocean.clampLut+BEACH_CLAMP5+(dg+63)*64;
          const uint8_t *bb=ocean.clampLut+(db+31)*32;
          for (int dy = 0; dy < 2; dy++) for (int dx = 0; dx < 2; dx++) {
            uint16_t &c = region[(r+dy)*320+x*2+dx];
            c = (rr[c>>11]<<11) | (gg[(c>>5)&63]<<5) | bb[c&31];
          }
        } else {
          for (int dy = 0; dy < 2; dy++) for (int dx = 0; dx < 2; dx++) {
            uint16_t &c = region[(r+dy)*320+x*2+dx];
            c = beachAdjust(c,dr,dg,db);
          }
        }
      }
    }
    composeUs += micros()-stamp;
    stamp = micros();
    if (width < 320) for (int r=0; r<rows; r++)
      memmove(region+(size_t)r*width, region+(size_t)r*320+left, width*sizeof(uint16_t));
    pushRegion(left,BEACH_TOP+band,width,rows,region);
    pushUs += micros()-stamp;
  }
  stamp = micros();
  drawBoat(boatStep,file);
  waveBoatUs = micros()-stamp;
  waveReadUs = readUs; waveComposeUs = composeUs; wavePushUs = pushUs;
  waveLastUs = micros()-began;
  waveMaxUs = max(waveMaxUs,waveLastUs);
  if (waveFrames) {
    waveGapMs = frameAt-wavePreviousFrameMs;
    waveMaxGapMs = max(waveMaxGapMs,waveGapMs);
    if (waveGapMs > 100) waveSlowFrames++;
  }
  wavePreviousFrameMs = frameAt;
  waveFrames++;
}

static void drawWave(int step, int boatStep, File &file) {
  if (!ocean.active || !region) return;
  if (ocean.version == 2 || ocean.version == 3) { drawBeach(step,boatStep,file); return; }
  const unsigned long began = micros();
  const int cosine = WAVE_SIN[(step*2+32)&127];
  for (int band = 0; band < WAVE_ROWS; band += 8) {
    const int rows = min(8, WAVE_ROWS-band);
    // One contiguous file read per band, rather than seeking for every pixel/row.
    if (!file.seek(8u+(uint32_t)(WAVE_TOP+band)*320u*2u) ||
        file.read((uint8_t *)region, rows*320u*2u) != rows*320u*2u) return;
    for (int r = 0; r < rows; r++) {
      const int yy = band+r, shore = waveEdge(WAVE_TOP+yy);
      const int tide = (128-cosine)*(10+36*yy/(WAVE_ROWS-1));
      const int ripple = 80+720*yy/(WAVE_ROWS-1);
      for (int x = max(0,shore-54); x < 320; x++) {
        const int idx = yy*320+x, bit = 1<<(idx&7);
        if (ocean.keep[idx/8]&bit) continue;
        // Monotonic falloff avoids folding the photograph into flat streaks.
        const int near = max(0,256-max(0,x-shore)*3);
        const int k = (WAVE_CARRIER[yy]+x/18)&127;
        const int dx = tide*near/256 + floorDivide(ripple*(WAVE_SIN[(k-step*2)&127]-WAVE_SIN[k]),128);
        const int dy = floorDivide(ripple*(WAVE_SIN[(k-step*2+32)&127]-WAVE_SIN[(k+32)&127]),160);
        int wet = max(0,min(255,floorDivide(((x-shore)*256+dx+768)*255,1536)));
        wet = wet*wet*(765-2*wet)/65025;
        if (!wet) continue;
        uint16_t c = waveSample(x*256+dx, yy*256+dy);
        const uint8_t foam = waveFoam(x, yy, shore, step);
        if (foam) c = blend565(c,0xffff,foam);
        if (ocean.glass[idx/8]&bit) c = blend565(c,ocean.colour,156);
        uint16_t &cell = region[r*320+x];
        cell = blend565(cell,c,wet);
      }
    }
    pushRegion(0,WAVE_TOP+band,320,rows,region);
  }
  waveLastUs = micros()-began;
  waveMaxUs = max(waveMaxUs,waveLastUs);
}

// Parse the ANIM trailer of a full-screen page. Anything wrong frees what was taken and the page stays static.
static bool readAnim(File &file, uint16_t w, uint16_t h) {
  freeAnim();
  if (w != 320 || h != 240) return false;
  const uint32_t base = 8u + (uint32_t)w * h * 2u;
  uint8_t tag[8];
  if (file.size() < base + 12 || !file.seek(base) || !readBytes(file, tag, 8)) return false;
  if (memcmp(tag,"SCRO",4) == 0) return readScroll(file,tag);
  if (memcmp(tag,"WAVE",4) == 0) return readWave(file,tag);
  if (memcmp(tag,"ANIM",4) != 0) return false;
  uint8_t head[4];
  if (!readBytes(file, head, 4)) return false;
  const int nSprites = head[0], nStars = head[1];
  if (nSprites > MAX_SPRITES || nStars > MAX_ANIM_STARS) return false;
  if (head[2]) {
    uint8_t m[16];
    if (!readBytes(file, m, 16)) return false;
    meteor.present = true;
    meteor.active = false;
    meteor.x0 = le16s(m); meteor.y0 = le16s(m + 2); meteor.x1 = le16s(m + 4); meteor.y1 = le16s(m + 6);
    meteor.periodMs = le16u(m + 8); meteor.head = le16u(m + 10); meteor.tail = le16u(m + 12);
    meteor.length = m[14] < 2 || m[14] > 24 ? 12 : m[14];
    meteor.speed = m[15] < 1 || m[15] > 12 ? 4 : m[15];
    meteor.lw = 0;
    meteor.next = animationClock.time(millis()) + 2500UL; // first one soon after the page appears
  }
  for (int i = 0; i < nStars; i++) {
    uint8_t e[10];
    if (!readBytes(file, e, 10)) { freeAnim(); return false; }
    AnimStar &st = animStars[animStarCount++];
    st.x = le16s(e); st.y = le16s(e + 2); st.base = le16u(e + 4); st.hi = le16u(e + 6); st.lo = le16u(e + 8);
    st.step = 0;
  }
  size_t biggest = 96 * 48;                          // room for the shooting star
  for (int i = 0; i < nSprites; i++) {
    uint8_t hdr[12];
    if (!readBytes(file, hdr, 12)) { freeAnim(); return false; }
    AnimSprite &s = sprites[spriteCount];
    s.pixels = nullptr;
    s.w = le16u(hdr); s.h = le16u(hdr + 2); s.x = le16s(hdr + 4); s.y = le16s(hdr + 6);
    s.frames = hdr[8]; s.steps = hdr[9]; s.stepMs = le16u(hdr + 10);
    if (s.w < 1 || s.w > 96 || s.h < 1 || s.h > 96 || s.frames < 1 || s.frames > 8 || s.steps < 1 ||
        s.steps > MAX_STEPS || s.stepMs < 40) { freeAnim(); return false; }
    int minDx = 0, maxDx = 0, minDy = 0, maxDy = 0;
    for (int k = 0; k < s.steps; k++) {
      uint8_t st[3];
      if (!readBytes(file, st, 3)) { freeAnim(); return false; }
      s.stepFrame[k] = st[0]; s.stepDx[k] = (int8_t)st[1]; s.stepDy[k] = (int8_t)st[2];
      minDx = min(minDx, (int)s.stepDx[k]); maxDx = max(maxDx, (int)s.stepDx[k]);
      minDy = min(minDy, (int)s.stepDy[k]); maxDy = max(maxDy, (int)s.stepDy[k]);
    }
    const size_t count = (size_t)s.frames * s.w * s.h;
    s.pixels = (uint16_t *)malloc(count * 2);
    if (!s.pixels) { freeAnim(); return false; }
    spriteCount++;                                   // counted before it is filled so freeAnim() releases it
    if (!readBytes(file, s.pixels, count * 2)) { freeAnim(); return false; }
    // the box this sprite can ever cover, kept inside the screen
    int bx = s.x + minDx, by = s.y + minDy;
    int bw = s.w * ANIM_SCALE + (maxDx - minDx), bh = s.h * ANIM_SCALE + (maxDy - minDy);
    if (bx < 0) { bw += bx; bx = 0; }
    if (by < 0) { bh += by; by = 0; }
    if (bx + bw > 320) bw = 320 - bx;
    if (by + bh > 240) bh = 240 - by;
    if (bw <= 0 || bh <= 0) { freeAnim(); return false; }
    s.bx = bx; s.by = by; s.bw = bw; s.bh = bh;
    s.lastStep = -1;
    biggest = max(biggest, (size_t)bw * bh);
  }
  region = (uint16_t *)malloc(biggest * 2);
  if (!region) { freeAnim(); return false; }
  regionPixels = biggest;
  animating = spriteCount > 0 || animStarCount > 0 || meteor.present;
  return animating;
}

// One shooting star: a bright head with a tail that fades into the sky, drawn on the 2x2 grid.
static void meteorTick(unsigned long now, File &file) {
  if (!meteor.present) return;
  if (!meteor.active) {
    if ((long)(now - meteor.next) < 0) return;
    meteor.active = true;
    meteor.hx = meteor.x0 + (int)random(max(1, (int)meteor.x1 - meteor.x0 + 1));
    meteor.hy = meteor.y0 + (int)random(max(1, (int)meteor.y1 - meteor.y0 + 1));
    meteor.ticks = 0;
    meteor.lw = 0;
  }
  meteor.hx += meteor.speed;
  meteor.hy += meteor.speed / 2;
  meteor.ticks++;
  const bool done = meteor.ticks > 60 || meteor.hx > 330 || meteor.hy > meteor.y1 + 36;   // gone before the skyline
  const int len = meteor.length;
  int x0 = min((int)meteor.hx - len * 2, (int)meteor.hx) - 2, y0 = min((int)meteor.hy - len, (int)meteor.hy) - 2;
  int x1 = (int)meteor.hx + 4, y1 = (int)meteor.hy + 4;
  int nx0 = x0, ny0 = y0, nx1 = x1, ny1 = y1;       // the box of this tick, then widened to the previous one
  if (meteor.lw > 0) {
    x0 = min(x0, (int)meteor.lx); y0 = min(y0, (int)meteor.ly);
    x1 = max(x1, (int)meteor.lx + meteor.lw); y1 = max(y1, (int)meteor.ly + meteor.lh);
  }
  x0 = max(x0, 0); y0 = max(y0, 0); x1 = min(x1, 320); y1 = min(y1, 240);
  nx0 = max(nx0, 0); ny0 = max(ny0, 0); nx1 = min(nx1, 320); ny1 = min(ny1, 240);
  const int rw = x1 - x0, rh = y1 - y0;
  if (rw <= 0 || rh <= 0 || (size_t)rw * rh > regionPixels || !readRect(file, x0, y0, rw, rh, region)) {
    meteor.active = false;
    meteor.lw = 0;
    meteor.next = now + meteor.periodMs;
    return;
  }
  if (!done) {
    for (int i = len; i >= 0; i--) {                 // tail first, so the head ends on top
      const int px = ((int)meteor.hx - i * 2) & ~1, py = ((int)meteor.hy - i) & ~1;
      if (px < x0 || py < y0 || px + 2 > x1 || py + 2 > y1) continue;
      for (int dy = 0; dy < 2; dy++) {
        for (int dx = 0; dx < 2; dx++) {
          uint16_t &cell = region[(size_t)(py + dy - y0) * rw + (px + dx - x0)];
          cell = i == 0 ? meteor.head : blend565(cell, meteor.tail, (uint8_t)(255 - (i * 150) / (len + 1)));
        }
      }
    }
  }
  pushRegion(x0, y0, rw, rh, region);
  if (done) {
    meteor.active = false;
    meteor.lw = 0;
    meteor.next = now + (unsigned long)meteor.periodMs * (70 + random(61)) / 100UL;
  } else {
    meteor.lx = nx0; meteor.ly = ny0; meteor.lw = nx1 - nx0; meteor.lh = ny1 - ny0;
  }
}

// Aim for an even 50 fps when a small wave region lets the board keep up.
// The independent animation clock keeps the wave duration and speed setting.
static bool beachFrameDue(unsigned long realNow) {
  return !ocean.active || ocean.version != 3 || !waveFrames || realNow-wavePreviousFrameMs >= 20UL;
}

static void animTick(unsigned long realNow) {
  static unsigned long lastTick = 0, lastStars = 0;
  if (!animating) return;
  const uint32_t now = animationClock.time(realNow);
  if (scrolling.active) {
    const int frameMs=scrolling.version >= 2 ? SCROLL_SMOOTH_MS : SCROLL_FRAME_MS;
    const unsigned long step=(now-scrolling.started)/frameMs;
    if (step != scrolling.lastStep) {
      drawScroll(step);
      scrolling.lastStep=step;
    }
    return;
  }
  // WAVE3 follows the animation clock directly; an independent throttle
  // would drift against it and delay intermediate poses.
  if (!(ocean.active && ocean.version == 3) && realNow - lastTick < (ocean.active ? 20UL : 40UL)) return;
  lastTick = realNow;
  if (ocean.active) {
    // WAVE3 keeps a 3.2 s water loop and a 6.4 s boat loop, with water
    // interpolated at the timestamp of each actual hardware frame.
    const unsigned long elapsed = now-ocean.started;
    const int step = ocean.version == 3
      ? (elapsed%BEACH_LOOP_MS)*(BEACH_FRAMES*BEACH_SUBSTEPS)/BEACH_LOOP_MS
      : (elapsed/WAVE_MS)%WAVE_STEPS;
    const int boatStep = ((now-ocean.started)/WAVE_MS)%WAVE_STEPS;
    if (step != ocean.lastStep) {
      if (!oceanFile) oceanFile = LittleFS.open(pagePath(page),"r");
      if (oceanFile) {
        if (ocean.version >= 2 && !ocean.cachedRows &&
            (waveCacheStatus == 1 || waveCacheStatus == 2) &&
            millis()-waveCacheAttemptAt >= 5000UL) cacheBeach(oceanFile);
        drawWave(step,boatStep,oceanFile);
        ocean.lastStep = step;
      }
    }
    return;
  }
  bool spriteDue = false;
  for (int i = 0; i < spriteCount; i++) {
    if ((int)((now / sprites[i].stepMs) % sprites[i].steps) != sprites[i].lastStep) spriteDue = true;
  }
  const bool meteorDue = meteor.present && (meteor.active || (long)(now - meteor.next) >= 0);
  if (spriteDue || meteorDue) {
    File file = LittleFS.open(pagePath(page), "r");
    if (file) {
      for (int i = 0; i < spriteCount; i++) {
        const int step = (int)((now / sprites[i].stepMs) % sprites[i].steps);
        if (step != sprites[i].lastStep) {
          sprites[i].lastStep = step;
          drawSpriteStep(sprites[i], step, file);
        }
      }
      meteorTick(now, file);
      file.close();
    }
  }
  if (animStarCount > 0 && now - lastStars >= 160) {
    lastStars = now;
    for (int k = 0; k < 2; k++) {
      AnimStar &st = animStars[random(animStarCount)];
      st.step = (st.step + 1) & 3;
      const uint16_t colour = st.step == 1 ? st.hi : (st.step == 3 ? st.lo : st.base);
      tft.fillRect(st.x, st.y, 2, 2, fixColor(colour));
    }
  }
}

static bool drawFrame(const String &path) {
  File file = LittleFS.open(path, "r");
  if (!file) return false;
  uint16_t w, h;
  if (!frameHeader(file, w, h)) { file.close(); return false; }
  int x0 = (tft.width() - w) / 2, y0 = (tft.height() - h) / 2;
  if (w < tft.width() || h < tft.height()) tft.fillScreen(TFT_BLACK);
  static uint16_t band[320 * BAND_ROWS];
  for (int y = 0; y < h; y += BAND_ROWS) {
    int rows = min(BAND_ROWS, h - y);
    size_t bytes = (size_t)w * rows * 2;
    if (file.read((uint8_t *)band, bytes) != bytes) break;
    if (swapRedBlue || swapBytes) {
      for (size_t i = 0; i < (size_t)w * rows; i++) {
        uint16_t p = band[i];
        if (swapBytes) p = (p >> 8) | (p << 8);
        if (swapRedBlue) p = ((p & 0xF800) >> 11) | (p & 0x07E0) | ((p & 0x001F) << 11);
        band[i] = p;
      }
    }
    tft.pushImage(x0, y0 + y, w, rows, band);
  }
  readStars(file, w, h);
  if (x0 == 0 && y0 == 0 && readAnim(file, w, h)) {
    // When quota text refreshes, resume the same camera position instead of
    // restarting the level at its first frame.
    if (scrolling.active && scrolling.lastStep) drawScroll(scrolling.lastStep);
    for (int i = 0; i < spriteCount; i++) {          // the first pose, so the page is complete at once
      sprites[i].lastStep = 0;
      drawSpriteStep(sprites[i], 0, file);
    }
  }
  file.close();
  animateStars = starCount > 0 && x0 == 0 && y0 == 0;   // full-screen pages only
  return true;
}

// The page dots are repainted with each scrolling frame. Cache the presence
// mask until storage or its configured capacity changes, instead of reopening
// all page files several times per frame.
static uint8_t indicatorPageMask = 0;
static bool indicatorMaskValid = false;
static int storedPages() {
  if (!indicatorMaskValid) {
    indicatorPageMask = 0;
    for (int n = 0; n < activePages; n++)
      if (LittleFS.exists(pagePath(n))) indicatorPageMask |= (1u << n);
    indicatorMaskValid = true;
  }
  int count = 0;
  for (int n = 0; n < activePages; n++) if (indicatorPageMask & (1u << n)) count++;
  return count;
}

// A quiet page marker: small neutral greys (never white), so it does not compete with the page.
static const uint16_t DOT_ACTIVE = 0x6B6D;   // about RGB(107,109,107)
static const uint16_t DOT_IDLE = 0x2965;     // about RGB(40,44,40)

static void drawRotationIndicator() {
  if (showingInfo || stale) return;
  // Bottom-left 29x9px; dim neutral ink, outside quota text and page dots.
  const int x = 4, y = tft.height()-10;
  const uint16_t ink = 0x7BEF, dim = 0x3186;
  tft.fillRect(x,y,29,9,TFT_BLACK);
  if (!rotationClock.mode) {
    tft.fillRect(x+2,y+2,1,5,dim); tft.fillRect(x+5,y+2,1,5,dim);
  } else {
    tft.drawCircle(x+4,y+4,3,dim);
    unsigned progress = rotationClock.progress(millis());
    for (int yy=-2; yy<=2; ++yy) for (int xx=-2; xx<=2; ++xx)
      if (xx*xx+yy*yy<=5 && (2-yy)*20 < (int)progress)
        tft.drawPixel(x+4+xx,y+4+yy,ink);
    if (rotationClock.mode==30) tft.drawLine(x+4,y+1,x+4,y+7,ink);
    tft.setTextColor(dim,TFT_BLACK); tft.setTextDatum(TL_DATUM);
    tft.drawString(rotationClock.mode==30 ? "30m" : "1h", x+10,y,1);
    if (!rotationClock.synced) tft.drawPixel(x+28,y+1,ink);
  }
}

static void saveSelection() {
  if (page != savedPage) { prefs.putInt("page", page); savedPage = page; }
}

static void restoreSelection() {
  page = prefs.getInt("page", 0);
  if (page < 0 || page >= activePages) page = 0;
  savedPage = page;
  rotationClock.setMode(prefs.getInt("cycle", 0), millis());
}

static void drawIndicator() {
  drawRotationIndicator();
  int count = storedPages();
  if (count < 2) return;
  int x = tft.width() - 8 - (count - 1) * 8;
  for (int n = 0, drawn = 0; n < activePages; n++) {
    if (!(indicatorPageMask & (1u << n))) continue;
    tft.fillCircle(x + drawn * 8, tft.height() - 5, 2, (n == page) ? DOT_ACTIVE : DOT_IDLE);
    drawn++;
  }
}

static void drawStale() {
  unsigned long minutes = haveBeat ? (millis() - lastBeat) / 60000UL : 0;
  message("NO DATA", haveBeat ? ("Last PC update: " + String(minutes) + " min ago") : "Waiting for the PC",
          "Outdated readings are hidden");
}

static void drawInfo() {
  if (paired()) message("AI Desk Display", "http://" + WiFi.localIP().toString(), "Paired with the PC");
  else message("AI Desk Display", "http://" + WiFi.localIP().toString(), "Waiting for PC pairing");
  tft.drawString(String(FIRMWARE), tft.width() / 2, 190, 2);
  tft.drawString("Tap: back | Hold " + String(connectHoldSeconds) + " s: connect", tft.width() / 2, 215, 2);
}

static void drawPage() {
  animationClock.setSpeed(millis(), pageSpeeds[page]);
  animateStars = false;
  freeAnim();
  if (showingInfo) { drawInfo(); return; }
  if (stale) { drawStale(); return; }
  if (!drawFrame(pagePath(page))) {
    message("Page " + String(page + 1) + " missing", "Waiting for the PC");
    return;
  }
  drawIndicator();
}

static int nextStoredPage(int from) {
  for (int step = 1; step <= activePages; step++) {
    int n = (from + step) % activePages;
    if (LittleFS.exists(pagePath(n))) return n;
  }
  return from;
}

static bool authorized() { return paired() && server.hasHeader("X-Token") && server.header("X-Token") == token; }

static void beat() {
  bool first = !haveBeat;
  haveBeat = true;
  lastBeat = millis();
  if (silentRestarts) { silentRestarts = 0; prefs.putInt("srest", 0); }
  if (first) {             // the PC found us: leave the address screen and show the data
    showingInfo = false;
    stale = false;
    if (!LittleFS.exists(pagePath(page))) page = nextStoredPage(page);
    saveSelection();
    drawPage();
  } else if (stale) {
    stale = false;
    drawPage();
  }
}

