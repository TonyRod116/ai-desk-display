// The boot splash: a run-length coded 256-colour picture streamed row by row.
static void drawSplash() {
  static uint16_t line[320];
  uint32_t i = 0;
  int x = 0, y = 0;
  while (i + 1 < SPLASH_RLE_LEN && y < 240) {
    uint8_t count = SPLASH_RLE[i];
    uint16_t color = SPLASH_PALETTE[SPLASH_RLE[i + 1]];
    i += 2;
    while (count-- && y < 240) {
      line[x++] = color;
      if (x == 320) {
        tft.pushImage(0, y, 320, 1, line);
        x = 0;
        y++;
      }
    }
  }
}

