static void freeAnim() {
  if (ocean.data) free(ocean.data);
  ocean.data = nullptr;
  ocean.active = false;
  for (int i = 0; i < spriteCount; i++) {
    if (sprites[i].pixels) free(sprites[i].pixels);
    sprites[i].pixels = nullptr;
  }
  spriteCount = 0;
  animStarCount = 0;
  meteor.present = false;
  meteor.active = false;
  if (region) free(region);
  region = nullptr;
  regionPixels = 0;
  animating = false;
}

// Read a w x h rectangle of the stored page (raw RGB565 as the PC sent it) into `out`.
static bool readRect(File &file, int x, int y, int w, int h, uint16_t *out) {
  if (x < 0 || y < 0 || w <= 0 || h <= 0 || x + w > 320 || y + h > 240) return false;
  for (int r = 0; r < h; r++) {
    if (!file.seek(8u + ((uint32_t)(y + r) * 320u + (uint32_t)x) * 2u)) return false;
    if (file.read((uint8_t *)(out + (size_t)r * w), (size_t)w * 2) != (size_t)w * 2) return false;
  }
  return true;
}

static void pushRegion(int x, int y, int w, int h, uint16_t *buf) {
  if (swapRedBlue || swapBytes) for (size_t i = 0; i < (size_t)w * h; i++) buf[i] = fixColor(buf[i]);
  tft.pushImage(x, y, w, h, buf);
}

static uint16_t blend565(uint16_t bg, uint16_t fg, uint8_t alpha) {   // alpha 0..255 of `fg`
  uint16_t r = (((bg >> 11) & 31) * (255 - alpha) + ((fg >> 11) & 31) * alpha) / 255;
  uint16_t g = (((bg >> 5) & 63) * (255 - alpha) + ((fg >> 5) & 63) * alpha) / 255;
  uint16_t b = ((bg & 31) * (255 - alpha) + (fg & 31) * alpha) / 255;
  return (r << 11) | (g << 5) | b;
}

// Compose one sprite pose over the stored background and push the whole box in one go, so it never flickers.
static void drawSpriteStep(AnimSprite &s, int step, File &file) {
  if (!region || (size_t)s.bw * s.bh > regionPixels) return;
  if (!readRect(file, s.bx, s.by, s.bw, s.bh, region)) return;
  const uint16_t *src = s.pixels + (size_t)(s.stepFrame[step] % s.frames) * s.w * s.h;
  const int ox = s.x + s.stepDx[step] * 1 - s.bx, oy = s.y + s.stepDy[step] * 1 - s.by;
  for (int sy = 0; sy < s.h; sy++) {
    for (int sx = 0; sx < s.w; sx++) {
      const uint16_t c = src[(size_t)sy * s.w + sx];
      if (c == ANIM_KEY) continue;
      for (int ky = 0; ky < ANIM_SCALE; ky++) {
        const int ry = oy + sy * ANIM_SCALE + ky;
        if (ry < 0 || ry >= (int)s.bh) continue;
        for (int kx = 0; kx < ANIM_SCALE; kx++) {
          const int rx = ox + sx * ANIM_SCALE + kx;
          if (rx >= 0 && rx < (int)s.bw) region[(size_t)ry * s.bw + rx] = c;
        }
      }
    }
  }
  pushRegion(s.bx, s.by, s.bw, s.bh, region);
}

static bool readBytes(File &file, void *dst, size_t n) { return file.read((uint8_t *)dst, n) == n; }
static int16_t le16s(const uint8_t *p) { return (int16_t)(p[0] | (p[1] << 8)); }
static uint16_t le16u(const uint8_t *p) { return (uint16_t)(p[0] | (p[1] << 8)); }

static int floorDivide(int n, int d) { return n >= 0 ? n / d : -((-n + d - 1) / d); }

static int waveEdge(int y) {
  static const int16_t coast[][2] = {{124,173},{132,158},{144,146},{152,126},
    {160,123},{170,108},{180,104},{190,94},{200,78},{210,72},{220,78},{239,77}};
  for (int i = 0; i < 11; i++) {
    if (y <= coast[i+1][0]) return coast[i][1] +
      floorDivide((coast[i+1][1]-coast[i][1])*(y-coast[i][0]), coast[i+1][0]-coast[i][0]);
  }
  return 77;
}

static bool readWave(File &file, const uint8_t *tag) {
  const uint32_t length = (uint32_t)tag[4] | ((uint32_t)tag[5]<<8) |
    ((uint32_t)tag[6]<<16) | ((uint32_t)tag[7]<<24);
  const uint32_t fixed = 12u + WAVE_ROWS*2u + 512u + 2u*(320u*WAVE_ROWS/8u);
  if (length < fixed || length > MAX_ANIM_BYTES || file.size() != 153616u+length) return false;
  ocean.data = (uint8_t *)malloc(length);
  if (!ocean.data) return false;
  if (!readBytes(file, ocean.data, length)) { freeAnim(); return false; }
  const uint8_t *p = ocean.data;
  if (p[0] != 1 || p[1] != 0 || le16u(p+2) != WAVE_TOP || le16u(p+4) != WAVE_ROWS ||
      le16u(p+6) != WAVE_MS || le16u(p+8) != WAVE_STEPS) { freeAnim(); return false; }
  ocean.colour = le16u(p+10);
  p += 12;
  uint32_t count = 0;
  for (int y = 0; y < WAVE_ROWS; y++, p += 2) {
    ocean.starts[y] = le16u(p);
    if (ocean.starts[y] >= 320) { freeAnim(); return false; }
    ocean.offsets[y] = count;
    count += 320-ocean.starts[y];
  }
  if (length != fixed+count) { freeAnim(); return false; }
  for (int i = 0; i < 256; i++, p += 2) ocean.palette[i] = le16u(p);
  ocean.indices = p;
  ocean.keep = p+count;
  ocean.glass = ocean.keep+320*WAVE_ROWS/8;
  regionPixels = 320*8;
  region = (uint16_t *)malloc(regionPixels*2);
  if (!region) { freeAnim(); return false; }
  ocean.lastStep = 0;
  ocean.started = millis();
  ocean.active = true;
  animating = true;
  waveLastUs = waveMaxUs = 0;
  return true;
}

static uint16_t wavePixel(int x, int y) {
  return ocean.palette[ocean.indices[ocean.offsets[y]+x-ocean.starts[y]]];
}

// Bilinear RGB565 sampling retains the photograph's fine one-pixel detail.
static uint16_t waveSample(int xq, int yq) {
  yq = max(0, min((WAVE_ROWS-1)*256, yq));
  const int y = yq/256, fy = yq%256, y1 = min(WAVE_ROWS-1, y+1);
  xq = max((int)max(ocean.starts[y], ocean.starts[y1])*256, min(319*256, xq));
  const int x = xq/256, fx = xq%256, x1 = min(319, x+1);
  const uint16_t a = wavePixel(x,y), b = wavePixel(x1,y), c = wavePixel(x,y1), d = wavePixel(x1,y1);
  uint16_t out = 0;
  const int shifts[] = {11,5,0}, masks[] = {31,63,31};
  for (int i = 0; i < 3; i++) {
    const int shift = shifts[i], mask = masks[i];
    const int ab = ((a>>shift)&mask)*(256-fx)+((b>>shift)&mask)*fx;
    const int cd = ((c>>shift)&mask)*(256-fx)+((d>>shift)&mask)*fx;
    out |= ((ab*(256-fy)+cd*fy+32768)/65536)<<shift;
  }
  return out;
}

static void drawWave(int step, File &file) {
  if (!ocean.active || !region) return;
  const unsigned long began = micros();
  const int cosine = WAVE_SIN[(step*2+32)&127];
  for (int band = 0; band < WAVE_ROWS; band += 8) {
    const int rows = min(8, WAVE_ROWS-band);
    // One contiguous file read per band, rather than seeking for every pixel/row.
    if (!file.seek(8u+(uint32_t)(WAVE_TOP+band)*320u*2u) ||
        file.read((uint8_t *)region, rows*320u*2u) != rows*320u*2u) return;
    if (step) for (int r = 0; r < rows; r++) {
      const int yy = band+r, shore = waveEdge(WAVE_TOP+yy);
      const int tide = (128-cosine)*(10+36*yy/(WAVE_ROWS-1));
      const int ripple = 80+720*yy/(WAVE_ROWS-1);
      for (int x = max(0,shore-54); x < 320; x++) {
        const int idx = yy*320+x, bit = 1<<(idx&7);
        if (ocean.keep[idx/8]&bit) continue;
        const int near = max(64,256-max(0,x-shore)*3);
        const int k = (WAVE_CARRIER[yy]+x/18)&127;
        const int dx = tide*near/256 + floorDivide(ripple*(WAVE_SIN[(k-step*2)&127]-WAVE_SIN[k]),128);
        const int dy = floorDivide(ripple*(WAVE_SIN[(k-step*2+32)&127]-WAVE_SIN[(k+32)&127]),160);
        int wet = max(0,min(255,floorDivide(((x-shore)*256+dx+768)*255,1536)));
        wet = wet*wet*(765-2*wet)/65025;
        if (!wet) continue;
        uint16_t c = waveSample(x*256+dx, yy*256+dy);
        if (ocean.glass[idx/8]&bit) c = blend565(c,ocean.colour,156);
        uint16_t &cell = region[r*320+x];
        cell = blend565(cell,c,wet);
      }
    }
    pushRegion(0,WAVE_TOP+band,320,rows,region);
  }
  waveLastUs = micros()-began;
  waveMaxUs = max(waveMaxUs,waveLastUs);
}

// Parse the ANIM trailer of a full-screen page. Anything wrong frees what was taken and the page stays static.
static bool readAnim(File &file, uint16_t w, uint16_t h) {
  freeAnim();
  if (w != 320 || h != 240) return false;
  const uint32_t base = 8u + (uint32_t)w * h * 2u;
  uint8_t tag[8];
  if (file.size() < base + 12 || !file.seek(base) || !readBytes(file, tag, 8)) return false;
  if (memcmp(tag,"WAVE",4) == 0) return readWave(file,tag);
  if (memcmp(tag,"ANIM",4) != 0) return false;
  uint8_t head[4];
  if (!readBytes(file, head, 4)) return false;
  const int nSprites = head[0], nStars = head[1];
  if (nSprites > MAX_SPRITES || nStars > MAX_ANIM_STARS) return false;
  if (head[2]) {
    uint8_t m[16];
    if (!readBytes(file, m, 16)) return false;
    meteor.present = true;
    meteor.active = false;
    meteor.x0 = le16s(m); meteor.y0 = le16s(m + 2); meteor.x1 = le16s(m + 4); meteor.y1 = le16s(m + 6);
    meteor.periodMs = le16u(m + 8); meteor.head = le16u(m + 10); meteor.tail = le16u(m + 12);
    meteor.length = m[14] < 2 || m[14] > 24 ? 12 : m[14];
    meteor.speed = m[15] < 1 || m[15] > 12 ? 4 : m[15];
    meteor.lw = 0;
    meteor.next = millis() + 2500UL;                 // the first one soon after the page appears
  }
  for (int i = 0; i < nStars; i++) {
    uint8_t e[10];
    if (!readBytes(file, e, 10)) { freeAnim(); return false; }
    AnimStar &st = animStars[animStarCount++];
    st.x = le16s(e); st.y = le16s(e + 2); st.base = le16u(e + 4); st.hi = le16u(e + 6); st.lo = le16u(e + 8);
    st.step = 0;
  }
  size_t biggest = 96 * 48;                          // room for the shooting star
  for (int i = 0; i < nSprites; i++) {
    uint8_t hdr[12];
    if (!readBytes(file, hdr, 12)) { freeAnim(); return false; }
    AnimSprite &s = sprites[spriteCount];
    s.pixels = nullptr;
    s.w = le16u(hdr); s.h = le16u(hdr + 2); s.x = le16s(hdr + 4); s.y = le16s(hdr + 6);
    s.frames = hdr[8]; s.steps = hdr[9]; s.stepMs = le16u(hdr + 10);
    if (s.w < 1 || s.w > 96 || s.h < 1 || s.h > 96 || s.frames < 1 || s.frames > 8 || s.steps < 1 ||
        s.steps > MAX_STEPS || s.stepMs < 40) { freeAnim(); return false; }
    int minDx = 0, maxDx = 0, minDy = 0, maxDy = 0;
    for (int k = 0; k < s.steps; k++) {
      uint8_t st[3];
      if (!readBytes(file, st, 3)) { freeAnim(); return false; }
      s.stepFrame[k] = st[0]; s.stepDx[k] = (int8_t)st[1]; s.stepDy[k] = (int8_t)st[2];
      minDx = min(minDx, (int)s.stepDx[k]); maxDx = max(maxDx, (int)s.stepDx[k]);
      minDy = min(minDy, (int)s.stepDy[k]); maxDy = max(maxDy, (int)s.stepDy[k]);
    }
    const size_t count = (size_t)s.frames * s.w * s.h;
    s.pixels = (uint16_t *)malloc(count * 2);
    if (!s.pixels) { freeAnim(); return false; }
    spriteCount++;                                   // counted before it is filled so freeAnim() releases it
    if (!readBytes(file, s.pixels, count * 2)) { freeAnim(); return false; }
    // the box this sprite can ever cover, kept inside the screen
    int bx = s.x + minDx, by = s.y + minDy;
    int bw = s.w * ANIM_SCALE + (maxDx - minDx), bh = s.h * ANIM_SCALE + (maxDy - minDy);
    if (bx < 0) { bw += bx; bx = 0; }
    if (by < 0) { bh += by; by = 0; }
    if (bx + bw > 320) bw = 320 - bx;
    if (by + bh > 240) bh = 240 - by;
    if (bw <= 0 || bh <= 0) { freeAnim(); return false; }
    s.bx = bx; s.by = by; s.bw = bw; s.bh = bh;
    s.lastStep = -1;
    biggest = max(biggest, (size_t)bw * bh);
  }
  region = (uint16_t *)malloc(biggest * 2);
  if (!region) { freeAnim(); return false; }
  regionPixels = biggest;
  animating = spriteCount > 0 || animStarCount > 0 || meteor.present;
  return animating;
}

// One shooting star: a bright head with a tail that fades into the sky, drawn on the 2x2 grid.
static void meteorTick(unsigned long now, File &file) {
  if (!meteor.present) return;
  if (!meteor.active) {
    if ((long)(now - meteor.next) < 0) return;
    meteor.active = true;
    meteor.hx = meteor.x0 + (int)random(max(1, (int)meteor.x1 - meteor.x0 + 1));
    meteor.hy = meteor.y0 + (int)random(max(1, (int)meteor.y1 - meteor.y0 + 1));
    meteor.ticks = 0;
    meteor.lw = 0;
  }
  meteor.hx += meteor.speed;
  meteor.hy += meteor.speed / 2;
  meteor.ticks++;
  const bool done = meteor.ticks > 60 || meteor.hx > 330 || meteor.hy > meteor.y1 + 36;   // gone before the skyline
  const int len = meteor.length;
  int x0 = min((int)meteor.hx - len * 2, (int)meteor.hx) - 2, y0 = min((int)meteor.hy - len, (int)meteor.hy) - 2;
  int x1 = (int)meteor.hx + 4, y1 = (int)meteor.hy + 4;
  int nx0 = x0, ny0 = y0, nx1 = x1, ny1 = y1;       // the box of this tick, then widened to the previous one
  if (meteor.lw > 0) {
    x0 = min(x0, (int)meteor.lx); y0 = min(y0, (int)meteor.ly);
    x1 = max(x1, (int)meteor.lx + meteor.lw); y1 = max(y1, (int)meteor.ly + meteor.lh);
  }
  x0 = max(x0, 0); y0 = max(y0, 0); x1 = min(x1, 320); y1 = min(y1, 240);
  nx0 = max(nx0, 0); ny0 = max(ny0, 0); nx1 = min(nx1, 320); ny1 = min(ny1, 240);
  const int rw = x1 - x0, rh = y1 - y0;
  if (rw <= 0 || rh <= 0 || (size_t)rw * rh > regionPixels || !readRect(file, x0, y0, rw, rh, region)) {
    meteor.active = false;
    meteor.lw = 0;
    meteor.next = now + meteor.periodMs;
    return;
  }
  if (!done) {
    for (int i = len; i >= 0; i--) {                 // tail first, so the head ends on top
      const int px = ((int)meteor.hx - i * 2) & ~1, py = ((int)meteor.hy - i) & ~1;
      if (px < x0 || py < y0 || px + 2 > x1 || py + 2 > y1) continue;
      for (int dy = 0; dy < 2; dy++) {
        for (int dx = 0; dx < 2; dx++) {
          uint16_t &cell = region[(size_t)(py + dy - y0) * rw + (px + dx - x0)];
          cell = i == 0 ? meteor.head : blend565(cell, meteor.tail, (uint8_t)(255 - (i * 150) / (len + 1)));
        }
      }
    }
  }
  pushRegion(x0, y0, rw, rh, region);
  if (done) {
    meteor.active = false;
    meteor.lw = 0;
    meteor.next = now + (unsigned long)meteor.periodMs * (70 + random(61)) / 100UL;
  } else {
    meteor.lx = nx0; meteor.ly = ny0; meteor.lw = nx1 - nx0; meteor.lh = ny1 - ny0;
  }
}

static void animTick(unsigned long now) {
  static unsigned long lastTick = 0, lastStars = 0;
  if (!animating || now - lastTick < (ocean.active ? 20UL : 40UL)) return;
  lastTick = now;
  if (ocean.active) {
    const int step = ((now-ocean.started)/WAVE_MS)%WAVE_STEPS;
    if (step != ocean.lastStep) {
      File file = LittleFS.open(pagePath(page),"r");
      if (file) {
        drawWave(step,file);
        ocean.lastStep = step;
        file.close();
      }
    }
    return;
  }
  bool spriteDue = false;
  for (int i = 0; i < spriteCount; i++) {
    if ((int)((now / sprites[i].stepMs) % sprites[i].steps) != sprites[i].lastStep) spriteDue = true;
  }
  const bool meteorDue = meteor.present && (meteor.active || (long)(now - meteor.next) >= 0);
  if (spriteDue || meteorDue) {
    File file = LittleFS.open(pagePath(page), "r");
    if (file) {
      for (int i = 0; i < spriteCount; i++) {
        const int step = (int)((now / sprites[i].stepMs) % sprites[i].steps);
        if (step != sprites[i].lastStep) {
          sprites[i].lastStep = step;
          drawSpriteStep(sprites[i], step, file);
        }
      }
      meteorTick(now, file);
      file.close();
    }
  }
  if (animStarCount > 0 && now - lastStars >= 160) {
    lastStars = now;
    for (int k = 0; k < 2; k++) {
      AnimStar &st = animStars[random(animStarCount)];
      st.step = (st.step + 1) & 3;
      const uint16_t colour = st.step == 1 ? st.hi : (st.step == 3 ? st.lo : st.base);
      tft.fillRect(st.x, st.y, 2, 2, fixColor(colour));
    }
  }
}

static bool drawFrame(const String &path) {
  File file = LittleFS.open(path, "r");
  if (!file) return false;
  uint16_t w, h;
  if (!frameHeader(file, w, h)) { file.close(); return false; }
  int x0 = (tft.width() - w) / 2, y0 = (tft.height() - h) / 2;
  if (w < tft.width() || h < tft.height()) tft.fillScreen(TFT_BLACK);
  static uint16_t band[320 * BAND_ROWS];
  for (int y = 0; y < h; y += BAND_ROWS) {
    int rows = min(BAND_ROWS, h - y);
    size_t bytes = (size_t)w * rows * 2;
    if (file.read((uint8_t *)band, bytes) != bytes) break;
    if (swapRedBlue || swapBytes) {
      for (size_t i = 0; i < (size_t)w * rows; i++) {
        uint16_t p = band[i];
        if (swapBytes) p = (p >> 8) | (p << 8);
        if (swapRedBlue) p = ((p & 0xF800) >> 11) | (p & 0x07E0) | ((p & 0x001F) << 11);
        band[i] = p;
      }
    }
    tft.pushImage(x0, y0 + y, w, rows, band);
  }
  readStars(file, w, h);
  if (x0 == 0 && y0 == 0 && readAnim(file, w, h)) {
    for (int i = 0; i < spriteCount; i++) {          // the first pose, so the page is complete at once
      sprites[i].lastStep = 0;
      drawSpriteStep(sprites[i], 0, file);
    }
  }
  file.close();
  animateStars = starCount > 0 && x0 == 0 && y0 == 0;   // full-screen pages only
  return true;
}

static int storedPages() {
  int count = 0;
  for (int n = 0; n < activePages; n++) if (LittleFS.exists(pagePath(n))) count++;
  return count;
}

// A quiet page marker: small neutral greys (never white), so it does not compete with the page.
static const uint16_t DOT_ACTIVE = 0x6B6D;   // about RGB(107,109,107)
static const uint16_t DOT_IDLE = 0x2965;     // about RGB(40,44,40)

static void drawRotationIndicator() {
  if (showingInfo || stale) return;
  // Bottom-left 29x9px; dim neutral ink, outside quota text and page dots.
  const int x = 4, y = tft.height()-10;
  const uint16_t ink = 0x7BEF, dim = 0x3186;
  tft.fillRect(x,y,29,9,TFT_BLACK);
  if (!rotationClock.mode) {
    tft.fillRect(x+2,y+2,1,5,dim); tft.fillRect(x+5,y+2,1,5,dim);
  } else {
    tft.drawCircle(x+4,y+4,3,dim);
    unsigned progress = rotationClock.progress(millis());
    for (int yy=-2; yy<=2; ++yy) for (int xx=-2; xx<=2; ++xx)
      if (xx*xx+yy*yy<=5 && (2-yy)*20 < (int)progress)
        tft.drawPixel(x+4+xx,y+4+yy,ink);
    if (rotationClock.mode==30) tft.drawLine(x+4,y+1,x+4,y+7,ink);
    tft.setTextColor(dim,TFT_BLACK); tft.setTextDatum(TL_DATUM);
    tft.drawString(rotationClock.mode==30 ? "30m" : "1h", x+10,y,1);
    if (!rotationClock.synced) tft.drawPixel(x+28,y+1,ink);
  }
}

static void saveSelection() {
  if (page != savedPage) { prefs.putInt("page", page); savedPage = page; }
}

static void restoreSelection() {
  page = prefs.getInt("page", 0);
  if (page < 0 || page >= activePages) page = 0;
  savedPage = page;
  rotationClock.setMode(prefs.getInt("cycle", 0), millis());
}

static void drawIndicator() {
  drawRotationIndicator();
  int count = storedPages();
  if (count < 2) return;
  int x = tft.width() - 8 - (count - 1) * 8;
  for (int n = 0, drawn = 0; n < activePages; n++) {
    if (!LittleFS.exists(pagePath(n))) continue;
    tft.fillCircle(x + drawn * 8, tft.height() - 5, 2, (n == page) ? DOT_ACTIVE : DOT_IDLE);
    drawn++;
  }
}

static void drawStale() {
  unsigned long minutes = haveBeat ? (millis() - lastBeat) / 60000UL : 0;
  message("NO DATA", haveBeat ? ("Last PC update: " + String(minutes) + " min ago") : "Waiting for the PC",
          "Outdated readings are hidden");
}

static void drawInfo() {
  if (paired()) message("AI Desk Display", "http://" + WiFi.localIP().toString(), "Paired with the PC");
  else message("AI Desk Display", "http://" + WiFi.localIP().toString(), "Waiting for PC pairing");
  tft.drawString(String(FIRMWARE), tft.width() / 2, 190, 2);
  tft.drawString("Tap: back | Hold 5 s: connect", tft.width() / 2, 215, 2);
}

static void drawPage() {
  animateStars = false;
  freeAnim();
  if (showingInfo) { drawInfo(); return; }
  if (stale) { drawStale(); return; }
  if (!drawFrame(pagePath(page))) {
    message("Page " + String(page + 1) + " missing", "Waiting for the PC");
    return;
  }
  drawIndicator();
}

static int nextStoredPage(int from) {
  for (int step = 1; step <= activePages; step++) {
    int n = (from + step) % activePages;
    if (LittleFS.exists(pagePath(n))) return n;
  }
  return from;
}

static bool authorized() { return paired() && server.hasHeader("X-Token") && server.header("X-Token") == token; }

static void beat() {
  bool first = !haveBeat;
  haveBeat = true;
  lastBeat = millis();
  if (silentRestarts) { silentRestarts = 0; prefs.putInt("srest", 0); }
  if (first) {             // the PC found us: leave the address screen and show the data
    showingInfo = false;
    stale = false;
    if (!LittleFS.exists(pagePath(page))) page = nextStoredPage(page);
    saveSelection();
    drawPage();
  } else if (stale) {
    stale = false;
    drawPage();
  }
}

