// POST /ping answers one character per page: 1 if it is stored. The PC resends the missing ones,
// so a board that was reflashed, formatted or replaced refills itself without anyone restarting the PC.
static void handlePing() {
  if (!authorized()) { server.send(401, "text/plain", "token"); return; }
  if (server.hasArg("clock")) {
    String value = server.arg("clock");
    bool valid = value.length() == 10;
    for (size_t i=0; valid && i<value.length(); ++i) valid = value[i]>='0' && value[i]<='9';
    if (!valid) { server.send(400,"text/plain","clock"); return; }
    uint64_t seconds = strtoull(value.c_str(), nullptr, 10);
    if (seconds < 1700000000ULL || seconds > 4102444800ULL) { server.send(400,"text/plain","clock"); return; }
    rotationClock.sync(seconds, millis());
  }
  String stored;
  for (int n = 0; n < PAGES; n++) stored += LittleFS.exists(pagePath(n)) ? '1' : '0';
  beat();
  server.send(200, "text/plain", stored);
}

static void applyDisplayOptions() {
  tft.setRotation(rotation);
  tft.invertDisplay(invertColors);
}

// POST /config?rotation=1|3&invert=0|1&swaprb=0|1&swapbytes=0|1 (token).
// Stored, so a panel that differs from the usual one needs no reflashing.
static void handleConfig() {
  if (!authorized()) { server.send(401, "text/plain", "token"); return; }
  // Validate both new options before applying either; invalid strings must not become zero.
  if (server.hasArg("cycle")) {
    String v = server.arg("cycle");
    if (v != "0" && v != "30" && v != "60") { server.send(400, "text/plain", "cycle"); return; }
  }
  if (server.hasArg("speed")) {
    String v = server.arg("speed");
    if (v != "75" && v != "100" && v != "125") { server.send(400, "text/plain", "speed"); return; }
  }
  if (server.hasArg("speedpage")) {
    String v = server.arg("speedpage");
    int n = v.toInt();
    if (!server.hasArg("speed") || n < 0 || n >= PAGES || v != String(n)) {
      server.send(400, "text/plain", "speedpage"); return;
    }
  }
  if (server.hasArg("holdmode") || server.hasArg("holdconnect")) {
    if (!server.hasArg("holdmode") || !server.hasArg("holdconnect")) { server.send(400,"text/plain","hold"); return; }
    String mode = server.arg("holdmode"), connect = server.arg("holdconnect");
    int m = mode.toInt(), c = connect.toInt();
    if (mode != String(m) || connect != String(c) || !validTouchSeconds(m,c)) {
      server.send(400,"text/plain","hold"); return;
    }
  }
  if (server.hasArg("cycle")) {
    int mode = server.arg("cycle").toInt();
    rotationClock.setMode(mode, millis());
    prefs.putInt("cycle", mode);
  }
  if (server.hasArg("speed")) {
    int rate = server.arg("speed").toInt();
    int n = server.hasArg("speedpage") ? server.arg("speedpage").toInt() : page;
    pageSpeeds[n] = rate;
    char key[12]; snprintf(key, sizeof(key), "speed%d", n);
    prefs.putInt(key, rate);
    if (n == page) animationClock.setSpeed(millis(), rate);
  }
  if (server.hasArg("holdmode")) {
    modeHoldSeconds = server.arg("holdmode").toInt();
    connectHoldSeconds = server.arg("holdconnect").toInt();
    prefs.putInt("holdmode", modeHoldSeconds);
    prefs.putInt("holdconnect", connectHoldSeconds);
  }
  if (server.hasArg("rotation")) {
    int value = server.arg("rotation").toInt();
    if (value != 1 && value != 3) { server.send(400, "text/plain", "rotation"); return; }
    rotation = value;
  }
  if (server.hasArg("pages")) {                    // how many of the slots are cycled; a deleted page stays out
    int value = server.arg("pages").toInt();
    if (value < 1 || value > PAGES) { server.send(400, "text/plain", "pages"); return; }
    activePages = value;
    indicatorMaskValid = false;
    prefs.putInt("np", activePages);
    if (page >= activePages) { page = 0; saveSelection(); }
  }
  if (server.hasArg("invert")) invertColors = server.arg("invert").toInt() != 0;
  if (server.hasArg("swaprb")) swapRedBlue = server.arg("swaprb").toInt() != 0;
  if (server.hasArg("swapbytes")) swapBytes = server.arg("swapbytes").toInt() != 0;
  prefs.putInt("rot", rotation);
  prefs.putBool("inv", invertColors);
  prefs.putBool("swap", swapRedBlue);
  prefs.putBool("bswap", swapBytes);
  applyDisplayOptions();
  drawPage();
  server.send(200, "text/plain", "OK");
}

// POST /pair?token=<16 hex>. An unpaired board is claimed by whoever asks first; a paired one
// only changes its token for a caller that already knows the current one.
static void handlePair() {
  String candidate = server.arg("token");
  bool valid = candidate.length() == 16;
  for (size_t i = 0; valid && i < candidate.length(); i++) {
    char c = candidate[i];
    valid = (c >= '0' && c <= '9') || (c >= 'a' && c <= 'f');
  }
  if (!valid) { server.send(400, "text/plain", "token"); return; }
  if (paired() && !authorized()) { server.send(401, "text/plain", "token"); return; }
  token = candidate;
  prefs.putString("token", token);
  if (showingInfo) drawPage();
  server.send(200, "text/plain", "OK");
}

static void handleUpdateDone() {
  bool allowed = updateAllowed, ok = updateOk;
  updateAllowed = false;
  updateOk = false;
  if (!allowed) { server.send(401, "text/plain", authorized() ? "touch" : "token"); drawPage(); return; }
  if (!ok) { server.send(400, "text/plain", "bad firmware"); drawPage(); return; }
  server.send(200, "text/plain", "OK");
  delay(500);
  ESP.restart();
}

// Token AND the address screen on display (a long touch on the board): code is not changed by
// anyone who only shares the network.
static void handleUpdateUpload() {
  HTTPUpload &upload = server.upload();
  if (upload.status == UPLOAD_FILE_START) {
    updateOk = false;
    updateStarted = false;
    updateAllowed = authorized() && showingInfo;
    if (!updateAllowed) return;
    message("Updating...", "Keep the display powered on");
    updateStarted = Update.begin(UPDATE_SIZE_UNKNOWN);
  } else if (upload.status == UPLOAD_FILE_WRITE) {
    if (updateStarted && Update.write(upload.buf, upload.currentSize) != upload.currentSize) {
      Update.abort();
      updateStarted = false;
    }
  } else if (upload.status == UPLOAD_FILE_END) {
    if (updateStarted) {
      updateOk = Update.end(true);
      updateStarted = false;
    }
  } else if (upload.status == UPLOAD_FILE_ABORTED) {
    if (updateStarted) Update.abort();
    updateStarted = false;
  }
}

static void handleShow() {
  if (!authorized()) { server.send(401, "text/plain", "token"); return; }
  int n = server.arg("n").toInt();
  if (n < 0 || n >= activePages || !LittleFS.exists(pagePath(n))) { server.send(404, "text/plain", "page"); return; }
  page = n;
  saveSelection();
  showingInfo = false;
  drawPage();
  server.send(200, "text/plain", "OK");
}

static void handleTouch(bool pressed, uint32_t now) {
  static uint32_t lastTap = 0;
  if (pressed && !touchHeld) { touchHeld=true; heldSince=now; }
  if (!pressed && touchHeld) {
    touchHeld=false;
    Gesture action = gesture(now-heldSince, modeHoldSeconds, connectHoldSeconds);
    if (action == Gesture::Connect) {
      ++longCount; showingInfo=true; confirmationUntil=0; drawPage();
    } else if (action == Gesture::Mode) {
      int mode=rotationClock.mode==0 ? 30 : rotationClock.mode==30 ? 60 : 0;
      rotationClock.setMode(mode,now); prefs.putInt("cycle",mode);
      showingInfo=false; confirmationUntil=now+2000; drawPage();
    } else if (action == Gesture::Page && now-lastTap>TAP_DEBOUNCE_MS) {
      lastTap=now; ++tapCount;
      if (showingInfo) showingInfo=false; else page=nextStoredPage(page);
      saveSelection(); confirmationUntil=0; drawPage();
    }
  }
}

// Shared by the main loop and bounded transfer chunks: do not recurse into HTTP.
static void serviceTouch(uint32_t now) {
  static uint32_t lastPoll = 0;
  if (updateStarted || now-lastPoll < 10) return;
  lastPoll = now;
  handleTouch(touch.touched(), now);
}

static void serviceRotation(uint32_t now) {
  if (rotationClock.due(now, !touchHeld && !showingInfo && !stale && haveBeat && now-lastBeat<=STALE_MS && !updateStarted)) {
    page=nextStoredPage(page); saveSelection(); drawPage();
  }
}

// ---- cooperative page transfers ---------------------------------------------------------
// WebServer handles a whole request synchronously. Keep drawing between chunks;
// never recurse into handleClient or a firmware update here. Touch handlers only
// change local selection/drawing; the current transfer retains its own file handle.
static void servicePageAnimation() {
  static unsigned long lastResidentTransferFrame = 0, lastTransferIndicator = 0;
  if (updateStarted) return;
  const unsigned long now = millis();
  serviceTouch(now);
  if (showingInfo) return;
  const bool expired = haveBeat ? now - lastBeat > STALE_MS : now > STALE_MS;
  if (expired && !stale) { stale = true; drawPage(); }
  serviceRotation(now);
  if (!stale) {
    const unsigned long before=scrolling.lastStep;
    const int beforeWave=ocean.lastStep;
    const bool resident=scrolling.active || ocean.active;
    // Budget time for networking. Include the draw itself in the interval,
    // and adapt to the board's measured cost.
    // A fast ocean can therefore draw more often without starving transfers.
    const unsigned long waveCostMs=(waveLastUs+999UL)/1000UL;
    const unsigned long minimum=ocean.version == 3 ? 50UL : 140UL;
    const unsigned long interval=ocean.active ? max(minimum, min(500UL, waveCostMs*2UL)) : 100UL;
    if ((!resident || !touchHeld) &&
        (!resident || now-lastResidentTransferFrame >= interval)) {
      animTick(now);
      if ((scrolling.active && scrolling.lastStep != before) ||
          (ocean.active && ocean.lastStep != beforeWave)) {
        lastResidentTransferFrame = now;
      }
    }
    if ((scrolling.active && scrolling.lastStep != before) ||
        (ocean.active && ocean.lastStep != beforeWave)) {
      drawIndicator();
      lastTransferIndicator = now;
    } else if (now-lastTransferIndicator >= 100UL) {
      drawRotationIndicator();
      lastTransferIndicator = now;
    }
  }
}

static void handlePageRead() {
  if (!authorized()) { server.send(401, "text/plain", "token"); return; }
  int n = server.arg("n").toInt();
  if (n < 0 || n >= PAGES || !LittleFS.exists(pagePath(n))) { server.send(404, "text/plain", "page"); return; }
  File file = LittleFS.open(pagePath(n), "r");
  if (!file) { server.send(404, "text/plain", "page"); return; }
  const size_t length = file.size();
  server.setContentLength(length);
  server.send(200, "application/octet-stream", "");
  auto client = server.client();
  uint8_t buffer[1024];
  size_t remaining = length;
  unsigned long progress = millis();
  while (remaining && client.connected()) {
    const size_t count = file.read(buffer, min(remaining, sizeof(buffer)));
    if (!count) { client.stop(); break; }
    size_t offset = 0;
    while (offset < count && client.connected()) {
      servicePageAnimation();
      // WiFiClient::write retries internally and can block for seconds on a slow
      // reader. A nonblocking socket write lets the animation run while waiting.
      const int sent = ::send(client.fd(), buffer + offset, count - offset, MSG_DONTWAIT);
      if (sent > 0) {
        offset += (size_t)sent;
        progress = millis();
      } else if (sent < 0 && errno != EAGAIN && errno != EWOULDBLOCK && errno != EINTR) {
        client.stop();
      }
      if (millis() - progress >= 2000UL) client.stop();
      delay(1);
    }
    remaining -= offset;
  }
  file.close();
}

static void handlePageUploadDone() {
  bool allowed = uploadAllowed, ok = uploadOk;
  uploadAllowed = false;   // flags belong to this request only
  uploadOk = false;
  if (!allowed) { server.send(401, "text/plain", "token"); return; }
  if (!ok) { server.send(400, "text/plain", "bad frame"); return; }
  beat();
  if (uploadPage == page && !showingInfo && !stale) {
    redrawPending = false;
    drawPage();
  }
  server.send(200, "text/plain", "OK");
}

static void handlePageUpload() {
  HTTPUpload &upload = server.upload();
  if (upload.status == UPLOAD_FILE_START) {
    uploadOk = false;
    uploadBytes = 0;
    uploadPage = server.arg("n").toInt();
    uploadAllowed = authorized() && uploadPage >= 0 && uploadPage < PAGES;
    if (!uploadAllowed) return;
    uploadFile = LittleFS.open("/incoming.tmp", "w");
  } else if (upload.status == UPLOAD_FILE_WRITE) {
    if (uploadAllowed && uploadFile) {
      servicePageAnimation();
      uploadBytes += upload.currentSize;
      if (uploadBytes <= MAX_PAGE_BYTES) uploadFile.write(upload.buf, upload.currentSize);
      servicePageAnimation();
    }
  } else if (upload.status == UPLOAD_FILE_END) {
    if (uploadAllowed && uploadFile) {
      uploadFile.close();
      // Only a well-formed frame replaces the stored page; anything else is dropped.
      File check = LittleFS.open("/incoming.tmp", "r");
      bool valid = false;
      if (check) {
        uint16_t w, h;
        valid = uploadBytes <= MAX_PAGE_BYTES && frameHeader(check, w, h);
        check.close();
      }
      if (valid) {
        // A resident beach keeps its source file open for smooth animation.
        // Release it before replacing that page, then draw the new one below.
        if (uploadPage == page && oceanFile) oceanFile.close();
        LittleFS.remove(pagePath(uploadPage));
        uploadOk = LittleFS.rename("/incoming.tmp", pagePath(uploadPage));
        indicatorMaskValid = false;
        if (uploadOk && uploadPage == page) redrawPending = true;
      } else {
        LittleFS.remove("/incoming.tmp");
      }
    }
  } else if (upload.status == UPLOAD_FILE_ABORTED) {
    if (uploadFile) uploadFile.close();
    LittleFS.remove("/incoming.tmp");
    uploadOk = false;
  }
}

static void onPortal(WiFiManager *) {
  message("Wi-Fi setup", "Join TokenTV-Display on your phone", "Then choose your home network");
}

void setup() {
  Serial.begin(115200);
  prefs.begin("tokentv", false);
  silentRestarts = prefs.getInt("srest", 0);
  activePages = prefs.getInt("np", PAGES);
  if (activePages < 1 || activePages > PAGES) activePages = PAGES;
  restoreSelection();
  int oldSpeed = prefs.getInt("speed", 100);
  if (!validAnimationSpeed(oldSpeed)) oldSpeed = 100;
  for (int n=0; n<PAGES; ++n) {
    char key[12]; snprintf(key, sizeof(key), "speed%d", n);
    int speed = prefs.getInt(key, oldSpeed);
    pageSpeeds[n] = validAnimationSpeed(speed) ? speed : 100;
  }
  animationClock.setSpeed(millis(), pageSpeeds[page]);
  int savedModeHold = prefs.getInt("holdmode", 2), savedConnectHold = prefs.getInt("holdconnect", 5);
  if (validTouchSeconds(savedModeHold, savedConnectHold)) {
    modeHoldSeconds = savedModeHold; connectHoldSeconds = savedConnectHold;
  }
  rotation = prefs.getInt("rot", 1);
  invertColors = prefs.getBool("inv", TOKENTV_INVERT_DEFAULT);
  swapRedBlue = prefs.getBool("swap", false);
  swapBytes = prefs.getBool("bswap", false);
  tft.init();
  applyDisplayOptions();   // landscape 320x240
  tft.setSwapBytes(true);  // pushImage expects natural (little-endian) RGB565 words
  tft.fillScreen(TFT_BLACK);
  const unsigned long splashStart = millis();
  drawSplash();
  splashStatus("Starting up...");

  // The touch controller sits on its own pins; pin the standard bus there first.
  // (The library's own SPI.begin() is then a no-op.) The display uses another bus.
  SPI.begin(TOUCH_SPI_CLK, TOUCH_SPI_MISO, TOUCH_SPI_MOSI, TOUCH_CS_PIN);
  pinMode(TOUCH_IRQ_PIN, INPUT);   // only observed (/info), no longer what wakes the reads
  touch.begin();
  touch.setRotation(1);

  if (!LittleFS.begin(true)) message("Storage error", "Could not mount LittleFS");
  LittleFS.remove("/incoming.tmp");

  token = prefs.getString("token", "");   // empty until the PC claims the board
  if (token.length() != 16) token = "";

  splashStatus("Connecting to Wi-Fi...");
  WiFiManager manager;
  manager.setAPCallback(onPortal);
  manager.setConnectTimeout(30);
  if (!manager.autoConnect("TokenTV-Display")) ESP.restart();
  // Always on mains: no modem sleep. With it some routers stop delivering unicast frames to an idle ESP32, which then
  // answers ARP yet neither ping nor HTTP ("associated but deaf", seen 2026-10-13 on this board).
  WiFi.setSleep(false);
  WiFi.setAutoReconnect(true);

  while (millis() - splashStart < 2200) delay(20);   // let the splash be seen, however fast the wifi was
  const char *headers[] = {"X-Token"};
  server.collectHeaders(headers, 1);
  server.on("/info", HTTP_GET, handleInfo);
  server.on("/ping", HTTP_POST, handlePing);
  server.on("/show", HTTP_POST, handleShow);
  server.on("/config", HTTP_POST, handleConfig);
  server.on("/pair", HTTP_POST, handlePair);
  server.on("/update", HTTP_POST, handleUpdateDone, handleUpdateUpload);
  server.on("/page", HTTP_GET, handlePageRead);
  server.on("/page", HTTP_POST, handlePageUploadDone, handlePageUpload);
  server.begin();

  showingInfo = true;   // first screen: where to point the PC at; the first heartbeat leaves it
  drawPage();
}

void loop() {
  server.handleClient();

  const unsigned long loopBegan = micros();
  static uint32_t lastCheck = 0;
  uint32_t now = millis();
  serviceTouch(now);
  serviceRotation(now);

  if (redrawPending) {                     // a fresh copy of the page being shown arrived: show it, not the old one
    redrawPending = false;
    if (!showingInfo && !stale && !updateStarted) drawPage();
  }
  bool residentFrame=false;
  if (!showingInfo && !stale) {
    const unsigned long before=scrolling.lastStep;
    const int beforeWave=ocean.lastStep;
    if ((!(scrolling.active || ocean.active) || !touchHeld) && beachFrameDue(now)) animTick(now);
    residentFrame=(scrolling.active && scrolling.lastStep != before) ||
                  (ocean.active && ocean.lastStep != beforeWave);
    if (residentFrame) {
      const unsigned long indicatorBegan = micros();
      drawIndicator();
      if (ocean.active) {
        waveIndicatorUs = micros()-indicatorBegan;
        waveLoopUs = micros()-loopBegan;
      }
    }
  }

  static unsigned long lastTwinkle = 0;
  if (animateStars && starCount > 0 && !showingInfo && !stale && now - lastTwinkle >= 50) {
    lastTwinkle = now;
    for (int k = 0; k < 6; k++) {         // six stars move a step each tick, so every star changes about once a
      Star &st = stars[random(starCount)];   // second: rest, a white spark with its cross, a glow, then nearly out
      st.step = (st.step + 1) % 6;
      paintStar(st, st.step >= 1 && st.step <= 3);   // steps 1-3 touch the cross (3 gives the page back)
    }
  }

  static uint32_t lastOverlay = 0;
  static bool overlayWasVisible = false;
  Gesture heldAction = touchHeld ? gesture(now-heldSince, modeHoldSeconds, connectHoldSeconds) : Gesture::None;
  bool preview = heldAction == Gesture::Mode || heldAction == Gesture::Connect;
  bool confirm = confirmationUntil && (int32_t)(confirmationUntil-now)>0;
  if (overlayWasVisible && !preview && !confirm) { confirmationUntil=0; drawPage(); }
  overlayWasVisible=preview || confirm;
  if (!showingInfo && !stale && (residentFrame || now-lastOverlay>=100)) {
    lastOverlay=now;
    if (!residentFrame) drawRotationIndicator();  // drawIndicator already painted it on a resident frame
    if (preview || confirm) {
      const char *text = preview ? (heldAction == Gesture::Connect ? "Release: connect" : "Release: auto-cycle") :
        rotationClock.mode==30 ? "Auto: every 30 min" : rotationClock.mode==60 ? "Auto: every hour" : "Fixed screen";
      tft.fillRect(74,211,172,18,TFT_BLACK);
      tft.setTextDatum(MC_DATUM); tft.setTextColor(0xAD55,TFT_BLACK);
      tft.drawString(text,160,220,2);
    }
  }

  if (now - lastCheck > 1000) {
    lastCheck = now;
    bool expired = haveBeat ? (now - lastBeat > STALE_MS) : (now > STALE_MS);
    if (expired && !stale && !showingInfo) { stale = true; drawPage(); }
  }
  // The PC beats about once a minute. Three silent minutes may mean the router still shows this board as
  // associated but no longer delivers to it (seen on this board): renew the link, at most every five minutes.
  // After ten silent minutes restart it, at most three times per silence, so a PC that is simply off does not
  // reboot it all night. Judged on the silence itself and not on the screen: after a boot the board sits on its
  // address screen and never becomes "stale", which is exactly when it used to give up.
  static unsigned long lastRenew = 0;
  const unsigned long silent = haveBeat ? now - lastBeat : now;
  if (silent > 180000UL && now - lastRenew > 300000UL) {
    lastRenew = now;
    linkRenewals++;
    WiFi.reconnect();
  }
  if (silent > 600000UL && silentRestarts < 3) {
    prefs.putInt("srest", silentRestarts + 1);
    ESP.restart();
  }
  // Wi-Fi loss uses the same grace period and persisted restart budget above.
  // A separate outage timer used to survive reconnections and bypass the cap.
}
